TEST=r"""
DO $verify$
DECLARE r record; linked integer;
BEGIN
 SELECT * INTO r FROM lf_ops.reglas WHERE codigo='B2B-RULE-AUTH-049';
 IF NOT FOUND OR r.estado<>'CANDIDATO' OR r.pendiente_decision IS NOT TRUE
    OR r.valor_config->>'owner_decision_ref'<>'L16-Q12|L16-Q06'
    OR r.valor_config->>'threshold_binding'<>'UNDEFINED_DO_NOT_ENFORCE'
    OR r.valor_config->>'window_duration'<>'UNDEFINED_DO_NOT_ENFORCE'
    OR r.valor_config->>'production_authorized'<>'false'
    OR r.valor_config->>'promotion_authorized'<>'false'
 THEN RAISE EXCEPTION 'E21_CANDIDATE_SCOPE_INVALID'; END IF;
 SELECT count(*) INTO linked FROM lf_ops.reglas_pantallas
 WHERE regla_id=r.id AND pantalla_id=51;
 IF linked<>1 THEN RAISE EXCEPTION 'E21_SCREEN_LINK_INVALID'; END IF;
 IF NOT EXISTS(SELECT 1 FROM lf_ops.reglas WHERE codigo='B2B-RULE-AUTH-047'
   AND pendiente_decision IS TRUE AND estado='CANDIDATO') THEN
   RAISE EXCEPTION 'E21_AUTH047_HISTORIC_STATUS_CHANGED'; END IF;
 IF EXISTS(SELECT 1 FROM lf_ops.reglas WHERE codigo='B2B-RULE-AUTH-049'
     AND valor_config ? 'numeric_threshold') THEN
   RAISE EXCEPTION 'E21_NUMERIC_THRESHOLD_INVENTED'; END IF;
END $verify$;
SELECT 'E21_CANDIDATE='||estado||':'||pendiente_decision
 FROM lf_ops.reglas WHERE codigo='B2B-RULE-AUTH-049';
SELECT 'E21_LINKS='||count(*) FROM lf_ops.reglas_pantallas rp
 JOIN lf_ops.reglas r ON r.id=rp.regla_id WHERE r.codigo='B2B-RULE-AUTH-049';
"""

class E21PgDual(unittest.TestCase):
    def test_e21_candidate_negative_and_rollback(self):
        self.assertIsNotNone(shutil.which("docker"),"DOCKER_REQUIRED")
        for version in ("17.6","18.7"):
            with self.subTest(version=version):
                name="lf-e21-"+uuid.uuid4().hex[:9]
                run=subprocess.run(["docker","run","-d","--rm","--name",name,
                    "-e","POSTGRES_PASSWORD=fixture-only","postgres:"+version],
                    capture_output=True,text=True,timeout=180)
                self.assertEqual(run.returncode,0,run.stderr)
                try:
                    for _ in range(90):
                        ready=subprocess.run(["docker","exec",name,"pg_isready","-U","postgres"],
                            capture_output=True,text=True,timeout=10)
                        if ready.returncode==0:
                            logs=subprocess.run(["docker","logs",name],
                                capture_output=True,text=True,timeout=10)
                            if "PostgreSQL init process complete; ready for start up." in (
                                logs.stdout+logs.stderr): break
                        time.sleep(.5)
                    self.assertEqual(ready.returncode,0,"PG_NOT_READY")
                    def psql(sql,negative=False):
                        r=subprocess.run(["docker","exec","-i",name,"psql",
                          "-X","-A","-t","-v","ON_ERROR_STOP=1","-U","postgres","-d","postgres"],
                          input=sql,capture_output=True,text=True,timeout=180)
                        if negative:self.assertNotEqual(r.returncode,0,r.stdout[-1500:])
                        else:self.assertEqual(r.returncode,0,r.stderr[-3500:]+"\n"+r.stdout[-3000:])
                        return r.stdout,r.stderr
                    # Wrong source screen must not create a rule.
                    out,err=psql("BEGIN;\n"+SCHEMA+
                        "UPDATE lf_ops.pantallas SET codigo='B2B-WRONG-001' WHERE id=51;\n"+
                        BODY+"\nROLLBACK;",negative=True)
                    self.assertIn("E21_SCREEN51_LOGIN_SOURCE_DRIFT",err)
                    # Missing AUTH-047 dependency must fail closed.
                    out,err=psql("BEGIN;\n"+SCHEMA+
                        "DELETE FROM lf_ops.reglas_pantallas;\n"+
                        BODY+"\nROLLBACK;",negative=True)
                    self.assertIn("E21_ORIGIN_PASSWORD_ATTEMPT_GAP_NOT_PROVEN",err)
                    out,err=psql("BEGIN;\n"+SCHEMA+BODY+"\n"+TEST+
                        "\nROLLBACK;\nSELECT 'E21_RESIDUE='||(to_regclass('lf_ops.reglas') IS NULL);\n")
                    for marker in ("E21_CANDIDATE=CANDIDATO:true",
                                   "E21_LINKS=1","E21_RESIDUE=true"):
                        self.assertIn(marker,out,marker+"\n"+out[-1500:])
                    print("PASS_E21_CANDIDATE_BLOCKED_POLICY_PG"+version+"_ROLLBACK",flush=True)
                finally:
                    subprocess.run(["docker","rm","-f",name],capture_output=True,timeout=30)

if __name__=="__main__":
    unittest.main()
