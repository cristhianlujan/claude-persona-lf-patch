class Auth001PriorityCandidatePGDual(unittest.TestCase):
    def test_pg17_pg18_apply_rollback_and_negative_drift(self):
        self.assertIsNotNone(shutil.which('docker'), 'DOCKER_REQUIRED_PG17_PG18')
        original = SQL.read_text(encoding='utf-8')
        self.assertEqual(original.count('INSERT INTO lf_ops.reglas\n'), 1)
        self.assertIn('INSERT INTO lf_ops.reglas_pantallas', original)
        self.assertTrue(original.startswith('-- LF B2B-AUTH-001:'))
        self.assertRegex(original, r'(?im)^BEGIN;\s*$')
        self.assertRegex(original, r'(?im)^COMMIT;\s*$')
        body = re.sub(r'(?im)^BEGIN;\s*$', '', original, count=1)
        body = re.sub(r'(?im)^COMMIT;\s*$', '', body, count=1)
        payload = json.loads(body.split('$candidates$')[1])
        self.assertEqual([x['codigo'] for x in payload], CODES)
        self.assertTrue(all(x['valor_config']['production_authorized'] is False for x in payload))
        self.assertEqual(sum(x['pendiente_decision'] for x in payload), 1)
        self.assertNotIn('UPDATE lf_ops.politicas_seguridad', original)
        self.assertNotIn('UPDATE lf_ops.reglas ', original)
        for pg in ('17.6','18.7'):
            with self.subTest(postgres=pg):
                name = 'lf-auth001-gaps-' + uuid.uuid4().hex[:10]
                created = subprocess.run(['docker','run','-d','--rm','--name',name,
                    '-e','POSTGRES_PASSWORD=fixture-only','postgres:'+pg],
                    capture_output=True,text=True,timeout=180)
                self.assertEqual(created.returncode, 0, created.stderr)
                try:
                    for _ in range(90):
                        ready = subprocess.run(['docker','exec',name,'pg_isready','-U','postgres'],
                            capture_output=True,text=True,timeout=12)
                        logs = subprocess.run(['docker','logs',name],
                            capture_output=True,text=True,timeout=10)
                        if ready.returncode == 0 and 'PostgreSQL init process complete; ready for start up.' in (logs.stdout+logs.stderr):
                            break
                        time.sleep(0.7)
                    else:
                        self.fail('POSTGRES_NOT_READY_'+pg)
                    def psql(statement, success=True):
                        r = subprocess.run(['docker','exec','-i',name,'psql','-X','-A','-t',
                                           '-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1'],
                            input=statement,capture_output=True,text=True,timeout=150)
                        if success: self.assertEqual(r.returncode, 0, r.stderr[-4000:])
                        else: self.assertNotEqual(r.returncode, 0, r.stdout)
                        return r
                    psql(SCHEMA)
                    prior = psql(READBACK)
                    self.assertIn('CANDIDATES=0:0',prior.stdout)
                    self.assertIn('LINKS=0',prior.stdout)
                    positive = psql('BEGIN;\n'+body+'\n'+READBACK+'\n'+body+'\n'+READBACK+'\nROLLBACK;\n'+READBACK)
                    self.assertEqual(positive.stdout.count('CANDIDATES=5:5'),2)
                    self.assertEqual(positive.stdout.count('LINKS=5'),2)
                    self.assertEqual(positive.stdout.count('PENDING=1'),2)
                    self.assertEqual(positive.stdout.count('POLICY20=CANDIDATO'),3)
                    self.assertIn('CANDIDATES=0:0',positive.stdout)
                    self.assertTrue(positive.stdout.rstrip().endswith('POLICY20=CANDIDATO'))
                    denied = psql("BEGIN;\nUPDATE lf_ops.politicas_seguridad SET status='VIGENTE' WHERE security_policy_id=20;\n"+body+"\nROLLBACK;",False)
                    self.assertIn('LF_AUTH001_SECURITY_POLICY_SOURCE_DRIFT',denied.stderr)
                    after = psql(READBACK)
                    self.assertIn('CANDIDATES=0:0',after.stdout)
                    self.assertIn('LINKS=0',after.stdout)
                    print('PASS_AUTH001_5_CANDIDATES_5_SCREEN51_LINKS_PG'+pg+'_ROLLBACK_DRIFT_GUARD')
                finally:
                    subprocess.run(['docker','rm','-f',name],capture_output=True,timeout=30)

