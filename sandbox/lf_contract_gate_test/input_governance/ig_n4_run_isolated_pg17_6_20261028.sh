#!/usr/bin/env bash
# LF IG G3 dev-only automatic disposable PostgreSQL 17.6 test runner.
# No Supabase, Router, production credentials or remote connection.
# Requires local PostgreSQL 17.6 binaries preinstalled on an isolated runner.
set -euo pipefail
umask 077

for cmd in python3 psql postgres initdb pg_ctl createdb mktemp; do
  command -v "$cmd" >/dev/null || { echo "NO_VERIFICADO: $cmd missing"; exit 2; }
done
if [[ "$(id -u)" -eq 0 ]]; then
  echo "BLOCK: initdb cannot run as root; use a nonprivileged isolated runner"
  exit 2
fi
if [[ "$(postgres --version)" != *"17.6"* ]]; then
  echo "BLOCK: source-hash verification requires PostgreSQL 17.6"
  exit 2
fi

data_dir="$(mktemp -d /tmp/lf_ig_n4_data_XXXXXXXX)"
socket_dir="$(mktemp -d /tmp/lf_ig_n4_socket_XXXXXXXX)"
started=0
cleanup() {
  if [[ "$started" -eq 1 ]]; then
    pg_ctl -D "$data_dir" -m immediate -w stop >/dev/null 2>&1 || true
  fi
  # Paths were exclusively generated by mktemp with the fixed private prefixes.
  [[ "$data_dir" == /tmp/lf_ig_n4_data_* ]] && rm -rf -- "$data_dir"
  [[ "$socket_dir" == /tmp/lf_ig_n4_socket_* ]] && rm -rf -- "$socket_dir"
}
trap cleanup EXIT

initdb -A trust -U ig_n4_local -D "$data_dir" --no-sync >/dev/null
# TCP explicitly disabled; only the freshly generated 0700 Unix socket exists.
pg_ctl -D "$data_dir" -l "$data_dir/server.log" -o "-c listen_addresses= -c unix_socket_directories=$socket_dir -c unix_socket_permissions=0700" -w start >/dev/null
started=1

export PGHOST="$socket_dir"
export PGUSER="ig_n4_local"
export PGDATABASE="postgres"
export PGPORT="5432"
export LF_IG_ISOLATED_PG_CONFIRMED="YES"
export LF_IG_EXPECTED_DATA_DIRECTORY="$data_dir"
unset PGSERVICE PGSERVICEFILE DATABASE_URL PGHOSTADDR PGOPTIONS || true

db="lf_ig_n4_isolated_$(date -u +%Y%m%d%H%M%S)_$$"
createdb "$db"
export PGDATABASE="$db"

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
python3 -m py_compile "$here/ig_n4_isolated_pg_verifier_20261028.py"
python3 "$here/ig_n4_isolated_pg_verifier_20261028.py"
echo "PASS_G3_LOCAL_CLUSTER_AUTODESTROYED_AFTER_EXIT"
