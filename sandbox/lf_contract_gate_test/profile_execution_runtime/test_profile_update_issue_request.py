import json
import os
from pathlib import Path
import runpy
import unittest

ROOT = Path(__file__).resolve().parents[3]
SCRIPT = ROOT / "scripts" / "lf_profile_update_issue_dispatch.py"
WORKFLOW = ROOT / ".github" / "workflows" / "lf-customer-profile-creator-governance-caller.yml"
MOD = runpy.run_path(str(SCRIPT), run_name="update_issue_test")
LABEL = "lf-profile-update-governed"
ENV = {"GITHUB_EVENT_NAME": "issues", "GITHUB_REPOSITORY": "o/r"}
INIT = {"schema_version": "LF_PROFILE_UPDATE_REQUEST_V1", "action": "profile_update_init",
        "target_code": "PERFIL-SYSTEMIC-ROOT-CAUSE-REPAIR-LF",
        "target_path": "profiles/systemic_root_cause_repair_lf/SKILL.md",
        "research_baseline_mode": "NOT_REQUIRED", "research_baseline_contract": None}
STEP = {"step_id": "router", "evidence_ref": "supabase://x",
        "evidence_payload": {"step_result": {}, "blocking_codes": []}}
BATCH = {"schema_version": "LF_PROFILE_UPDATE_REQUEST_V1", "action": "profile_update_record_batch",
         "execution_id": "EXEC-ACTUALIZACION-PERFIL-LF-OIDC-1234", "steps": [STEP]}
A40, B40, Z40 = "a" * 40, "b" * 40, "0" * 40
PROOF = {"schema_version": "LF_PROFILE_UPDATE_REQUEST_V1", "action": "profile_evolution_proof", "mode": "compare",
         "profile_slug": "systemic_root_cause_repair_lf", "base_sha": A40, "candidate_sha": B40}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def request(payload=None, body=None, label=LABEL, state="open", pr=None, repo_url="https://api.github.com/repos/o/r", env=None):
    event = {"action": "labeled", "label": {"name": label},
             "issue": {"state": state, "pull_request": pr, "repository_url": repo_url,
                       "body": json.dumps(payload) if body is None else body}}
    return MOD["governed_request"](event, env or ENV)


class TriggerTest(unittest.TestCase):
    def test_wrong_label_state_pr_repo_or_event_rejected(self):
        for kw in ({"label": "other"}, {"state": "closed"}, {"pr": {}},
                   {"repo_url": "https://api.github.com/repos/x/y"},
                   {"env": {**ENV, "GITHUB_EVENT_NAME": "workflow_dispatch"}}):
            with self.assertRaises(ValueError):
                request(INIT, **kw)

    def test_footer_allowed_other_trailing_data_rejected(self):
        raw = json.dumps(INIT)
        for ok in (raw, raw + "\n", raw + FOOTER):
            self.assertEqual(request(body=ok)["action"], "profile_update_init")
        for tail in ("\nextra", "\n\n---\n_Generated by [Other](https://evil.example)_", FOOTER + "\nmore"):
            with self.assertRaises(ValueError):
                request(body=raw + tail)

    def test_bad_bodies_rejected(self):
        for raw in ("", "   ", "[]", "not json", json.dumps({**INIT, "pad": "x" * 65000})):
            with self.assertRaises((ValueError, json.JSONDecodeError)):
                request(body=raw)


class InitTest(unittest.TestCase):
    def test_valid_init_maps_to_dispatch_inputs(self):
        self.assertEqual(request(INIT), {
            "action": "profile_update_init", "target_code": INIT["target_code"],
            "target_path": INIT["target_path"], "research_baseline_mode": "NOT_REQUIRED",
            "research_baseline_contract_json": ""})

    def test_pre_research_requires_contract_object(self):
        ok = {**INIT, "research_baseline_mode": "PRE_RESEARCH_ALWAYS", "research_baseline_contract": {"contract_version": "X"}}
        self.assertEqual(json.loads(request(ok)["research_baseline_contract_json"]), {"contract_version": "X"})
        for bad in ({**ok, "research_baseline_contract": None}, {**ok, "research_baseline_contract": []},
                    {**INIT, "research_baseline_contract": {"a": 1}}):
            with self.assertRaises(ValueError):
                request(bad)

    def test_target_and_schema_rejections(self):
        for patch in ({"target_code": "profile-x"}, {"target_code": "PERFIL-X;rm"}, {"target_path": "../etc/passwd"},
                      {"target_path": "profiles/a/../../x"}, {"target_path": "/profiles/a/SKILL.md"},
                      {"target_path": "docs/a.md"}, {"research_baseline_mode": "OTHER"},
                      {"schema_version": "V0"}, {"action": "source_canary_only"}):
            with self.assertRaises(ValueError):
                request({**INIT, **patch})
        extra = {**INIT, "executor_mode": "CLAUDE_NATIVE"}
        with self.assertRaises(ValueError):
            request(extra)
        missing = {k: v for k, v in INIT.items() if k != "target_path"}
        with self.assertRaises(ValueError):
            request(missing)


class BatchTest(unittest.TestCase):
    def test_valid_batch(self):
        out = request(BATCH)
        self.assertEqual(out["execution_id"], BATCH["execution_id"])
        self.assertEqual(json.loads(out["steps_json"]), BATCH["steps"])

    def test_batch_rejections(self):
        dup = [STEP, STEP]
        no_ref = [{**STEP, "evidence_ref": ""}]
        no_blocking = [{**STEP, "evidence_payload": {"step_result": {}}}]
        bad_id = [{**STEP, "step_id": "Bad-ID"}]
        for patch in ({"execution_id": "EXEC-x"}, {"execution_id": "x"}, {"steps": []}, {"steps": dup},
                      {"steps": no_ref}, {"steps": no_blocking}, {"steps": bad_id}, {"steps": "[]"},
                      {"steps": [STEP] * 65}, {"target_code": "PERFIL-X"}):
            with self.assertRaises(ValueError):
                request({**BATCH, **patch})

    def test_oversize_batch_rejected(self):
        big = {**STEP, "evidence_payload": {"step_result": {"pad": "x" * 61000}, "blocking_codes": []}}
        with self.assertRaises(ValueError):
            request({**BATCH, "steps": [big]})


class ProofTest(unittest.TestCase):
    def test_valid_compare_and_measure(self):
        self.assertEqual(request(PROOF), {"action": "profile_evolution_proof", "mode": "compare",
                                          "profile_slug": "systemic_root_cause_repair_lf", "base_sha": A40, "candidate_sha": B40})
        self.assertEqual(request({**PROOF, "mode": "measure", "candidate_sha": Z40})["mode"], "measure")

    def test_proof_rejections(self):
        for patch in ({"mode": "other"}, {"profile_slug": "../x"}, {"profile_slug": "Bad"}, {"base_sha": "abc"},
                      {"candidate_sha": "G" * 40}, {"candidate_sha": A40}, {"mode": "measure"},
                      {"target_code": "PERFIL-X"}):
            with self.assertRaises(ValueError):
                request({**PROOF, **patch})

    def test_proof_dispatches_proof_workflow_without_action_input(self):
        cmd = MOD["dispatch_command"](request(PROOF))
        self.assertEqual(cmd[:6], ["gh", "workflow", "run", "lf-profile-evolution-proof.yml", "--ref", "main"])
        self.assertNotIn("action=profile_evolution_proof", cmd)
        self.assertIn("mode=compare", cmd)
        self.assertIn("candidate_sha=" + B40, cmd)


class DeployTest(unittest.TestCase):
    DEPLOY = {"schema_version": "LF_PROFILE_UPDATE_REQUEST_V1", "action": "profile_runtime_deploy"}

    def test_valid_deploy_dispatches_only_the_fixed_governed_action(self):
        cmd = MOD["dispatch_command"](request(self.DEPLOY))
        self.assertEqual(cmd, ["gh", "workflow", "run", "lf-edge-deploy-credential-readback.yml", "--ref", "main",
                               "-f", "action=deploy-profile-runtime"])

    def test_deploy_accepts_no_parameters(self):
        for extra in ({"function": "other-fn"}, {"ref": "x"}, {"execution_id": "EXEC-12345678"}, {"target_code": "PERFIL-X"}):
            with self.assertRaises(ValueError):
                request({**self.DEPLOY, **extra})
        with self.assertRaises(ValueError):
            request({"schema_version": "LF_PROFILE_UPDATE_REQUEST_V1", "action": "deploy-caller"})


class DispatchTest(unittest.TestCase):
    def test_command_targets_registered_workflow_on_main_only(self):
        cmd = MOD["dispatch_command"](request(INIT))
