import json
import os
from pathlib import Path
import runpy
import unittest
from unittest.mock import patch

SCRIPT = Path(__file__).resolve().parents[3] / "scripts" / "lf_profile_router_admit.py"
CTX = {
    "schema_version": "LF_ROUTER_EXECUTION_PIPELINE_V1",
    "status": "GATE2_DERIVED_PENDING_GOVERNED_ADMISSION",
    "transport_mode": "CONTEXT_TRANSPORT",
}


class RouterAdmitRequestTest(unittest.TestCase):
    def run_request(self, context, mode):
        env = {"ROUTER_CONTEXT_JSON": context if isinstance(context, str) else json.dumps(context),
               "EXECUTOR_MODE": mode}
        with patch.dict(os.environ, env, clear=True):
            return runpy.run_path(str(SCRIPT), run_name="admit_test")["governed_request"]()

    def test_both_native_modes_accepted(self):
        for mode in ("GPT_NATIVE", "CLAUDE_NATIVE"):
            self.assertEqual(self.run_request(CTX, mode), (CTX, mode))

    def test_remote_and_unknown_modes_rejected(self):
        for mode in ("REMOTE_API", "", "claude_native", "OTHER"):
            with self.assertRaises(ValueError):
                self.run_request(CTX, mode)

    def test_bad_envelopes_rejected(self):
        for key, value in (("schema_version", "X"), ("status", "READY"), ("transport_mode", "READ_ONLY_CONTEXT")):
            with self.assertRaises(ValueError):
                self.run_request({**CTX, key: value}, "CLAUDE_NATIVE")

    def test_non_object_empty_and_oversize_rejected(self):
        for raw in ("[]", "", json.dumps({**CTX, "pad": "x" * 61000})):
            with self.assertRaises(ValueError):
                self.run_request(raw, "CLAUDE_NATIVE")


class RouterAdmitIssueTest(unittest.TestCase):
    LABEL = "lf-profile-admit-governed"

    def issue_request(self, body=None, label=None, state="open", pr=None, repo_url=None):
        import tempfile
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "event.json"
            payload = {"schema_version": "LF_PROFILE_ROUTER_ADMIT_REQUEST_V1",
                       "router_context": CTX, "executor_mode": "CLAUDE_NATIVE"}
            event = {"action": "labeled", "label": {"name": label or self.LABEL},
                     "issue": {"state": state, "pull_request": pr,
                               "repository_url": repo_url or "https://api.github.com/repos/o/r",
                               "body": json.dumps(payload) if body is None else body}}
            path.write_text(json.dumps(event), encoding="utf-8")
            env = {"LF_PROFILE_ADMIT_REQUEST_MODE": "ISSUE", "GITHUB_EVENT_NAME": "issues",
                   "GITHUB_REPOSITORY": "o/r", "GITHUB_EVENT_PATH": str(path)}
            with patch.dict(os.environ, env, clear=True):
                return runpy.run_path(str(SCRIPT), run_name="admit_issue_test")["governed_request"]()

    def test_valid_issue(self):
        self.assertEqual(self.issue_request(), (CTX, "CLAUDE_NATIVE"))

    def test_wrong_label_state_pr_or_repo_rejected(self):
        for kw in ({"label": "other"}, {"state": "closed"}, {"pr": {}}, {"repo_url": "https://api.github.com/repos/x/y"}):
            with self.assertRaises(ValueError):
                self.issue_request(**kw)

    def test_platform_footer_allowed_but_other_trailing_data_rejected(self):
        payload = json.dumps({"schema_version": "LF_PROFILE_ROUTER_ADMIT_REQUEST_V1",
                              "router_context": CTX, "executor_mode": "CLAUDE_NATIVE"})
        footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        self.assertEqual(self.issue_request(body=payload + footer), (CTX, "CLAUDE_NATIVE"))
        self.assertEqual(self.issue_request(body=payload + "\n"), (CTX, "CLAUDE_NATIVE"))
        for tail in ("\nextra", "\n\n---\n_Generated by [Other](https://evil.example)_", footer + "\nmore"):
            with self.assertRaises(ValueError):
                self.issue_request(body=payload + tail)

    def test_bad_body_rejected(self):
        for body in ("not json", "[]", json.dumps({"schema_version": "X"}),
                     json.dumps({"schema_version": "LF_PROFILE_ROUTER_ADMIT_REQUEST_V1",
                                 "router_context": CTX, "executor_mode": "REMOTE_API"}),
                     json.dumps({"schema_version": "LF_PROFILE_ROUTER_ADMIT_REQUEST_V1",
                                 "router_context": CTX, "executor_mode": "CLAUDE_NATIVE", "extra": 1})):
            with self.assertRaises((ValueError, json.JSONDecodeError)):
                self.issue_request(body=body)



class RouterAdmitOutcomeTest(unittest.TestCase):
    def script(self):
        return runpy.run_path(str(SCRIPT), run_name="outcome_test")

    def admitted(self, http_status=200, outcome="PROFILE_HANDOFF_READY", **overrides):
        result = {
            "status": "PROFILE_HANDOFF_READY",
            "write_performed": False,
            "execution_id": None,
            "executor_mode": "GPT_NATIVE",
            "profile_code": "PERFIL-PRODUCT-DIRECTOR-LF",
            "router_profile_handoff": {"fingerprint_sha256": "a" * 64},
            "next_action": "EJECUCION_PERFIL_LF_BEGIN_REQUIRED",
        }
        result.update(overrides)
        return self.script()["admission_success"](
            http_status, {"outcome": outcome, "result": result}, "GPT_NATIVE")

    def executed(self, http_status=200, outcome="NATIVE_EXECUTION_READY", **overrides):
        result = {
            "status": "NATIVE_EXECUTION_READY",
            "gate2_materialized": True,
            "executor_mode": "GPT_NATIVE",
            "execution_id": "EXEC-PROFILE-GATE2-AABBCCDDEEFF112233445566",
            "profile_code": "PERFIL-PRODUCT-DIRECTOR-LF",
            "next_action": "EXECUTE_PROFILE_IN_AUTHORIZED_NATIVE_CONTEXT",
        }
        result.update(overrides)
        return self.script()["execution_success"](
            http_status, {"outcome": outcome, "result": result}, "GPT_NATIVE")

    def test_stage6_handoff_without_execution_is_accepted(self):
        self.assertTrue(self.admitted())

    def test_stage6_rejects_claim_of_execution_or_write(self):
        for override in (
            {"execution_id": "EXEC-PROFILE-ILLEGAL"},
            {"write_performed": True},
            {"router_profile_handoff": None},
            {"status": "NATIVE_EXECUTION_READY"},
            {"next_action": "EXECUTE_PROFILE_IN_AUTHORIZED_NATIVE_CONTEXT"},
            {"executor_mode": "REMOTE_API"},
        ):
            self.assertFalse(self.admitted(**override))

    def test_stage7_requires_real_execution(self):
        self.assertTrue(self.executed())
        for override in (
            {"execution_id": None}, {"execution_id": ""},
            {"gate2_materialized": False}, {"status": "PENDING"},
            {"executor_mode": "REMOTE_API"}, {"next_action": "OTHER"},
        ):
            self.assertFalse(self.executed(**override))

    def test_status_and_http_fail_closed(self):
        self.assertFalse(self.admitted(http_status=409))
        self.assertFalse(self.admitted(outcome="BLOCKED"))
        self.assertFalse(self.executed(http_status=409))
        self.assertFalse(self.executed(outcome="PROFILE_HANDOFF_READY"))


class RouterAdmitSequenceTest(unittest.TestCase):
    def test_main_invokes_stage6_then_stage7_only_after_handoff(self):
        m = runpy.run_path(str(SCRIPT), run_name="unit_test")
        handoff = {
            "outcome": "PROFILE_HANDOFF_READY",
            "result": {"status": "PROFILE_HANDOFF_READY",
                       "write_performed": False, "execution_id": None,
                       "executor_mode": "GPT_NATIVE",
                       "profile_code": "PERFIL-PRODUCT-DIRECTOR-LF",
                       "router_profile_handoff": {"fingerprint_sha256": "a"*64},
                       "next_action": "EJECUCION_PERFIL_LF_BEGIN_REQUIRED"},
        }
        execution = {
            "outcome": "NATIVE_EXECUTION_READY",
            "result": {"status": "NATIVE_EXECUTION_READY",
                       "gate2_materialized": True, "executor_mode": "GPT_NATIVE",
                       "execution_id": "EXEC-PROFILE-GATE2-TEST",
                       "profile_code": "PERFIL-PRODUCT-DIRECTOR-LF",
                       "next_action": "EXECUTE_PROFILE_IN_AUTHORIZED_NATIVE_CONTEXT"},
        }
        calls = []
        def fake_call(url, body, headers):
            calls.append(body["action"])
            if len(calls) == 1:
                return 200, handoff
            return 200, execution
        m["governed_request"] = lambda: (CTX, "GPT_NATIVE")
        # runpy functions retain the initial global namespace; patch that explicitly.
        main = m["main"]
        with patch.dict(main.__globals__, {
            "governed_request": lambda: (CTX, "GPT_NATIVE"),
            "oidc": lambda: "mock-token",
            "call_json": fake_call,
            "EDGE_URL": "https://example.invalid",
        }):
            self.assertEqual(main(), 0)
        self.assertEqual(calls, ["router_profile_admit_context_v2",
                                 "profile_execution_begin_from_router_context_v1"])

        calls.clear()
        handoff["result"]["write_performed"] = True
        with patch.dict(main.__globals__, {
            "governed_request": lambda: (CTX, "GPT_NATIVE"),
            "oidc": lambda: "mock-token",
            "call_json": fake_call,
            "EDGE_URL": "https://example.invalid",
        }):
            self.assertEqual(main(), 1)
        self.assertEqual(calls, ["router_profile_admit_context_v2"])


if __name__ == "__main__":
    unittest.main()
