#!/usr/bin/env python3
"""Real PostgreSQL 17.6 concurrency/apply/rollback proof with no LF credentials.

Requires an ephemeral PostgreSQL Docker container from the existing CI service.
Does not connect to Supabase, and never changes official business records.
"""
import concurrent.futures
import json
import os
from pathlib import Path
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[3]
FIXTURE = ROOT / "sandbox/lf_contract_gate_test/db_write_transport/lf_skill_invoker_pg17_fixture_v1.sql"
MIGRATION = ROOT / "supabase/migrations/20261109101500_lf_skill_invoker_idempotent_replay_v1.sql"
BASELINE_MD5 = "289ef129239ba1a4cbb33314f4484f4b"
CONTAINER = os.environ.get("PG_CONTAINER", "")


def sql(query: str, database: str = "postgres", must_succeed: bool = True) -> str:
    cmd = ["docker", "exec", "-i", CONTAINER, "psql", "-X", "-A", "-t", "-q",
           "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-d", database]
    proc = subprocess.run(cmd, input=query, capture_output=True, text=True, timeout=35)
    if must_succeed and proc.returncode != 0:
        raise AssertionError("POSTGRESQL_FAILED:" + proc.stderr[-1400:])
    if not must_succeed and proc.returncode == 0:
        raise AssertionError("EXPECTED_POSTGRESQL_FAILURE_NOT_OBSERVED")
    return proc.stdout.strip() if must_succeed else proc.stderr.strip()


def check(condition: bool, code: str) -> None:
    if not condition:
        raise AssertionError(code)
    print(code, flush=True)


def call(rule: str, database: str = "postgres") -> dict:
    # rule generated by test fixture literals, never user input.
    statement = ("SELECT public.lf_skill_invoke_v1('RULE_UPDATE_APPLY',"
                 "'EXEC-PROFILE-GATE2-TEST12345678',"
                 "'{\"regla_codigo\":\"" + rule + "\"}'::jsonb);")
    return json.loads(sql(statement, database))


def main() -> None:
    if not CONTAINER:
        raise RuntimeError("POSTGRESQL_ISOLATED_CONTAINER_REQUIRED")
    original = FIXTURE.read_text(encoding="utf-8")
    candidate = MIGRATION.read_text(encoding="utf-8")
    sql(original)
    baseline = sql("SELECT md5(pg_get_functiondef('public.lf_skill_invoke_v1(text,text,jsonb)'::regprocedure))")
    check(baseline == BASELINE_MD5, "PASS_ORIGINAL_FUNCTION_EXACT_PG17_MD5")

    # Real historical duplicate evidence must remain unmodified; only new rows
    # get the partial unique index. Use the same hash algorithm as real handler.
    sql("""
    INSERT INTO public.lf_skill_invocation_v1
      (skill_run_id,skill_code,parent_execution_id,profile_code,status,input_sha256,created_at)
    SELECT 'RUN-LEGACY-'||s::text,'RULE_UPDATE_APPLY',
      'EXEC-PROFILE-GATE2-TEST12345678','PERFIL-PRODUCT-DIRECTOR-LF',
      'COMPLETED',
      encode(extensions.digest(convert_to('{"regla_codigo":"HIST"}'::jsonb::text,'UTF8'),'sha256'),'hex'),
      '2026-11-05T00:00:00Z'::timestamptz
    FROM generate_series(1,2) s;
    """)
    sql(candidate)
    check(sql("SELECT count(*) FROM pg_indexes WHERE schemaname='public' AND indexname='lf_skill_invocation_v1_new_parent_skill_input_uniq'") == "1",
          "PASS_EXACT_UNIQUE_INDEX_PRESENT")
    check("SKILL_REPLAY_AMBIGUOUS_HISTORY" in sql(
        "SELECT pg_get_functiondef('public.lf_skill_invoke_v1(text,text,jsonb)'::regprocedure)"),
        "PASS_INVOKER_DEPLOYED_IN_ISOLATED_PG")

    # Real two-session race. Handler sleeps 550ms before invocation insert.
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
        futs = [pool.submit(call, "NEW") for _ in range(2)]
        receipts = [f.result(timeout=25) for f in futs]
    check(all(r.get("status") == "COMPLETED" for r in receipts),
          "PASS_TWO_SESSIONS_COMPLETED")
    check(len({r["skill_run_id"] for r in receipts}) == 1 and
          len({r["child_execution_id"] for r in receipts}) == 1,
          "PASS_TWO_SESSIONS_SAME_INVOCATION_AND_CHILD")
    check({r.get("replay") for r in receipts} == {None, True},
          "PASS_RACE_HAS_ONE_FIRST_AND_ONE_REPLAY")
    inv = sql("""SELECT count(*)
      FROM public.lf_skill_invocation_v1
      WHERE input_sha256=encode(extensions.digest(convert_to(
        '{"regla_codigo":"NEW"}'::jsonb::text,'UTF8'),'sha256'),'hex')""")
    children = sql("""SELECT count(*) FROM public.lf_operation_execution
      WHERE operation_code='ACTUALIZACION_REGLA_LF'
        AND target_code='NEW' AND created_by_execution_id='EXEC-PROFILE-GATE2-TEST12345678'""")
    check(inv == "1" and children == "1", "PASS_ONE_PERSISTED_INVOCATION_ONE_CHILD")

    again = call("NEW")
    check(again.get("replay") is True and
          again.get("skill_run_id") == receipts[0]["skill_run_id"] and
          again.get("child_execution_id") == receipts[0]["child_execution_id"],
          "PASS_LOST_RESPONSE_REPLAY_SAME_IDS")

    history = call("HIST")
    check(history.get("status") == "BLOCKED" and
          history.get("blocking_code") == "SKILL_REPLAY_AMBIGUOUS_HISTORY",
          "PASS_AMBIGUOUS_HISTORY_FAIL_CLOSED")
    check(sql("""SELECT count(*) FROM public.lf_skill_invocation_v1
      WHERE skill_run_id LIKE 'RUN-LEGACY-%'""") == "2",
          "PASS_HISTORICAL_ROWS_UNTOUCHED")

    sql("""UPDATE public.lf_profile_write_authority_v1 SET status='RETIRED'
      WHERE profile_code='PERFIL-PRODUCT-DIRECTOR-LF'""")
    denied = call("DENY")
    check(denied.get("status") == "BLOCKED" and
          denied.get("blocking_code") == "SKILL_NOT_AUTHORIZED_FOR_PROFILE",
          "PASS_UNAUTHORIZED_OPERATION_BLOCKED")
    check(sql("""SELECT count(*) FROM public.lf_operation_execution
      WHERE target_code='DENY'""") == "0",
          "PASS_UNAUTHORIZED_HAS_NO_CHILD")
    sql("""UPDATE public.lf_profile_write_authority_v1 SET status='ACTIVE'
      WHERE profile_code='PERFIL-PRODUCT-DIRECTOR-LF'""")
    sql("""UPDATE public.lf_operation_execution SET status='COMPLETED'
      WHERE execution_id='EXEC-PROFILE-GATE2-TEST12345678'""")
    parent_closed = call("CLOSED")
    check(parent_closed.get("status") == "BLOCKED" and
          parent_closed.get("blocking_code") == "PARENT_EXECUTION_NOT_ACTIVE",
          "PASS_PARENT_TERMINAL_REJECTS_FRESH_CHILD")
    check(sql("""SELECT count(*) FROM public.lf_operation_execution
      WHERE target_code='CLOSED'""") == "0", "PASS_PARENT_TERMINAL_NO_CHILD")

    # Transaction-scoped rollback of the real migration on an independent
    # freshly bootstrapped database, not a SQL parse/static simulation.
    proc = subprocess.run(["docker", "exec", CONTAINER, "createdb", "-U", "postgres",
                           "lf_skill_idem_rollback_probe"], capture_output=True, text=True,
                          timeout=20)
    check(proc.returncode == 0, "PASS_ROLLBACK_DATABASE_CREATED")
    sql(original, "lf_skill_idem_rollback_probe")
    rollback_result = sql("BEGIN;\n" + candidate + "\nROLLBACK;\n"
                          + "SELECT md5(pg_get_functiondef('public.lf_skill_invoke_v1(text,text,jsonb)'::regprocedure));\n"
                          + "SELECT count(*) FROM pg_indexes WHERE schemaname='public' AND indexname='lf_skill_invocation_v1_new_parent_skill_input_uniq';",
                          "lf_skill_idem_rollback_probe")
    lines = [line.strip() for line in rollback_result.splitlines() if line.strip()]
    check(lines[-2:] == [BASELINE_MD5, "0"], "PASS_TRANSACTIONAL_ROLLBACK_RESTORES_FUNCTION_AND_INDEX")
    check(sql("SELECT count(*) FROM public.lf_skill_invocation_v1", "lf_skill_idem_rollback_probe") == "0",
          "PASS_ROLLBACK_NO_INVOCATION_RESIDUE")
    print(json.dumps({"status": "ISOLATED_PG17_CONCURRENCY_ROLLBACK_PASS",
                      "source_function_md5": BASELINE_MD5,
                      "credentialless": True,
                      "production_write": False}), flush=True)


if __name__ == "__main__":
    main()
