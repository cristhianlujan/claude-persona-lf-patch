  RAISE EXCEPTION 'TERMINAL_ITEM_MUTATION_WAS_ALLOWED';
 EXCEPTION WHEN OTHERS THEN
  IF SQLERRM='TERMINAL_ITEM_MUTATION_WAS_ALLOWED' THEN RAISE; END IF;
  IF position('SALY_CHAT_TERMINAL_ITEM_IMMUTABLE' in SQLERRM)=0 THEN RAISE; END IF;
 END;
