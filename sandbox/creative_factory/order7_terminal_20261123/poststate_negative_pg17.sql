  UPDATE saly.creative_orders SET status='PLANIFICADO' WHERE id=7;
  RAISE EXCEPTION 'TERMINAL_ORDER_MUTATION_WAS_ALLOWED';
 EXCEPTION WHEN OTHERS THEN
  IF SQLERRM='TERMINAL_ORDER_MUTATION_WAS_ALLOWED' THEN RAISE; END IF;
  IF position('SALY_CHAT_TERMINAL_ORDER_IMMUTABLE' in SQLERRM)=0 THEN RAISE; END IF;
 END;
END $post$;
