BEGIN
 IF (SELECT status FROM saly.creative_orders WHERE id=7)<>'TERMINADO'
  OR (SELECT status FROM saly.creative_order_items WHERE id=10)<>'TERMINADO'
  OR (SELECT count(*) FROM saly.creative_runs WHERE order_id=7 OR item_id=10)<>0
  OR (SELECT count(*) FROM saly.creative_order_items WHERE order_id=7)<>1
  OR (SELECT count(*) FROM saly.creative_orders WHERE status='PLANIFICADO' AND code='SALY_ADELANTO_V015_SINGLE_20261123')<>1
 THEN RAISE EXCEPTION 'POSITIVE_TERMINAL_READBACK_FAILED'; END IF;
