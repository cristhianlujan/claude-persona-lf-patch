from public.lf_input_exploration_records r where r.governance_status in ('OPEN','READY_FOR_INPUT_GOVERNANCE');
revoke all on public.v_lf_input_exploration_pending from public,anon,authenticated;
grant select on public.v_lf_input_exploration_pending to service_role;

do $patch$
declare v_def text; v_new text;
 p text := $p$v_expected:=case upper(p_action_code) when 'REGLA_CREATE' then 'CREACION_REGLA_LF' else 'ACTUALIZACION_REGLA_LF' end;
 select * into v_exec$p$;
 r text := $p$v_expected:=case upper(p_action_code) when 'REGLA_CREATE' then 'CREACION_REGLA_LF' else 'ACTUALIZACION_REGLA_LF' end;
 perform 1 from public.lf_operation_mode_bindings b where b.operation_code=v_expected and b.task_mode=case when upper(p_action_code)='REGLA_CREATE' then 'CREATE_NEW' else 'REMEDIATE_EXISTING' end and b.execution_mode='GOVERNED' and b.status='ACTIVE' and b.allowed and b.write_allowed and b.destination_kind='CANONICAL_CANDIDATE' and b.input_completeness='COMPLETE_REQUIRED';
 if not found then raise exception 'LF_REGLA_GOVERNED_MODE_BINDING_MISSING:%',v_expected; end if;
 select * into v_exec$p$;
begin
 select pg_get_functiondef('public.lf_regla_candidate_write_v1(text,text,text,text,text,text,text,jsonb,boolean,text)'::regprocedure) into v_def;
 if strpos(v_def,p)=0 then raise exception 'LF_REGLA_MODE_PATCH_SOURCE_DRIFT'; end if;
 v_new:=replace(v_def,p,r); execute v_new;
end $patch$;

do $post$
declare n int; r jsonb;
begin
 select count(*) into n from public.lf_task_mode_catalog where status='ACTIVE'; if n<>3 then raise exception 'LF_TASK_MODE_COUNT_FAIL:%',n; end if;
 select count(*) into n from public.lf_execution_mode_catalog where status='ACTIVE'; if n<>3 then raise exception 'LF_EXECUTION_MODE_COUNT_FAIL:%',n; end if;
 select count(*) into n from public.lf_operation_mode_bindings where status='ACTIVE'; if n<>5 then raise exception 'LF_OPERATION_MODE_BINDING_COUNT_FAIL:%',n; end if;
 select count(*) into n from pg_class c join pg_namespace ns on ns.oid=c.relnamespace where ns.nspname='public' and c.relname in ('lf_task_mode_catalog','lf_execution_mode_catalog','lf_operation_mode_bindings','lf_input_exploration_records','lf_input_exploration_events') and c.relrowsecurity; if n<>5 then raise exception 'LF_MODE_RLS_COUNT_FAIL:%',n; end if;
 if has_function_privilege('anon','public.lf_resolve_operation_mode_v1(text,text,text)','EXECUTE') or has_function_privilege('authenticated','public.lf_resolve_operation_mode_v1(text,text,text)','EXECUTE') then raise exception 'LF_MODE_RESOLVER_ACL_FAIL'; end if;
 if has_function_privilege('anon','public.lf_input_exploration_capture_v1(text,text,text,jsonb,uuid,text,integer,jsonb,boolean)','EXECUTE') or has_function_privilege('authenticated','public.lf_input_exploration_capture_v1(text,text,text,jsonb,uuid,text,integer,jsonb,boolean)','EXECUTE') then raise exception 'LF_EXPLORATION_CAPTURE_ACL_FAIL'; end if;
 r:=public.lf_resolve_operation_mode_v1('CREACION_REGLA_LF','CREATE_NEW','EXPLORATION'); if r->>'status'<>'READY' or r->>'destination_kind'<>'EXPLORATION_STORE' then raise exception 'LF_MODE_RESOLVE_POST_FAIL:%',r; end if;
 r:=public.lf_resolve_operation_mode_v1('ACTUALIZACION_REGLA_LF','EVALUATE_EXISTING','EXPLORATION'); if r->>'status'<>'READY' or (r->>'write_allowed')::boolean then raise exception 'LF_MODE_EVALUATE_POST_FAIL:%',r; end if;
 if position('LF_REGLA_GOVERNED_MODE_BINDING_MISSING' in pg_get_functiondef('public.lf_regla_candidate_write_v1(text,text,text,text,text,text,text,jsonb,boolean,text)'::regprocedure))=0 then raise exception 'LF_REGLA_GOVERNED_BINDING_PATCH_MISSING'; end if;
end $post$;
