create or replace function public.lf_resolve_operation_mode_v1(p_operation_code text,p_task_mode text,p_execution_mode text)
returns jsonb language plpgsql security invoker set search_path=pg_catalog,public as $$
declare v_b public.lf_operation_mode_bindings%rowtype; v_t public.lf_task_mode_catalog%rowtype; v_m public.lf_execution_mode_catalog%rowtype;
begin
 if btrim(coalesce(p_operation_code,''))='' or btrim(coalesce(p_task_mode,''))='' or btrim(coalesce(p_execution_mode,''))='' then return jsonb_build_object('status','BLOCKED','blocking_code','MODE_IDENTITY_MISSING'); end if;
 select * into v_t from public.lf_task_mode_catalog where task_mode=upper(p_task_mode) and status='ACTIVE';
 if not found then return jsonb_build_object('status','BLOCKED','blocking_code','TASK_MODE_NOT_ACTIVE','task_mode',upper(p_task_mode)); end if;
 select * into v_m from public.lf_execution_mode_catalog where execution_mode=upper(p_execution_mode) and status='ACTIVE';
 if not found then return jsonb_build_object('status','BLOCKED','blocking_code','EXECUTION_MODE_NOT_ACTIVE','execution_mode',upper(p_execution_mode)); end if;
 select * into v_b from public.lf_operation_mode_bindings where operation_code=p_operation_code and task_mode=v_t.task_mode and execution_mode=v_m.execution_mode and status='ACTIVE';
 if not found or not v_b.allowed then return jsonb_build_object('status','BLOCKED','blocking_code','OPERATION_MODE_NOT_ALLOWED','operation_code',p_operation_code,'task_mode',v_t.task_mode,'execution_mode',v_m.execution_mode); end if;
 return jsonb_build_object('status','READY','operation_code',v_b.operation_code,'task_mode',v_b.task_mode,'execution_mode',v_b.execution_mode,'write_allowed',v_b.write_allowed,'destination_kind',v_b.destination_kind,'input_completeness',v_b.input_completeness,'canonical_state',v_b.canonical_state,'required_existing_state',v_b.required_existing_state,'allows_partial_input',v_m.allows_partial_input,'canonical_write_allowed',v_m.canonical_write_allowed,'runtime_allowed',v_m.runtime_allowed,'promotion_allowed',v_m.promotion_allowed,'reference_source',v_m.reference_source);
end $$;
revoke all on function public.lf_resolve_operation_mode_v1(text,text,text) from public,anon,authenticated;
grant execute on function public.lf_resolve_operation_mode_v1(text,text,text) to service_role;

create or replace function public.lf_input_exploration_capture_v1(p_execution_id text,p_asset_type text,p_task_mode text,p_partial_payload jsonb,p_exploration_id uuid default null,p_target_code text default null,p_source_pantalla_id integer default null,p_source_context jsonb default '{}'::jsonb,p_mark_ready boolean default false)
returns jsonb language plpgsql security invoker set search_path=pg_catalog,public,lf_ops as $$
declare v_exec public.lf_operation_execution%rowtype; v_mode jsonb; v_rec public.lf_input_exploration_records%rowtype; v_snapshot jsonb; v_context jsonb; v_missing jsonb; v_revision integer; v_status text; v_id uuid;
begin
 if btrim(coalesce(p_execution_id,''))='' or upper(coalesce(p_asset_type,''))<>'REGLA' then raise exception 'LF_EXPLORATION_IDENTITY_INVALID'; end if;
 if p_partial_payload is null or jsonb_typeof(p_partial_payload)<>'object' or p_partial_payload='{}'::jsonb then raise exception 'LF_EXPLORATION_PARTIAL_PAYLOAD_REQUIRED'; end if;
 if p_source_context is null or jsonb_typeof(p_source_context)<>'object' then raise exception 'LF_EXPLORATION_SOURCE_CONTEXT_INVALID'; end if;
 select * into v_exec from public.lf_operation_execution where execution_id=p_execution_id;
 if not found or v_exec.status<>'IN_PROGRESS' or v_exec.target_type<>'REGLA' then raise exception 'LF_EXPLORATION_EXECUTION_INVALID'; end if;
 v_mode:=public.lf_resolve_operation_mode_v1(v_exec.operation_code,upper(p_task_mode),'EXPLORATION');
 if v_mode->>'status'<>'READY' or coalesce((v_mode->>'write_allowed')::boolean,false) is not true or v_mode->>'destination_kind'<>'EXPLORATION_STORE' then raise exception 'LF_EXPLORATION_MODE_WRITE_NOT_ALLOWED:%',coalesce(v_mode->>'blocking_code','NO_WRITE'); end if;
 if p_source_pantalla_id is not null and not exists(select 1 from lf_ops.pantallas where id=p_source_pantalla_id) then raise exception 'LF_EXPLORATION_SCREEN_NOT_FOUND:%',p_source_pantalla_id; end if;
 v_status:=case when coalesce(p_mark_ready,false) then 'READY_FOR_INPUT_GOVERNANCE' else 'OPEN' end;
 if upper(p_task_mode)='CREATE_NEW' then
   if p_exploration_id is not null then raise exception 'LF_EXPLORATION_CREATE_ID_MUST_BE_NULL'; end if;
   v_snapshot:=p_partial_payload; v_context:=p_source_context; v_revision:=1;
   select coalesce(jsonb_agg(k order by ord),'[]'::jsonb) into v_missing from (values (1,'codigo'),(2,'categoria'),(3,'titulo'),(4,'descripcion')) x(ord,k) where nullif(btrim(coalesce(v_snapshot->>k,'')),'') is null;
   insert into public.lf_input_exploration_records(asset_type,task_mode,execution_mode,target_code,source_pantalla_id,source_context,partial_payload,missing_fields,governance_status,revision,created_by_execution_id,updated_by_execution_id)
   values('REGLA','CREATE_NEW','EXPLORATION',coalesce(nullif(btrim(p_target_code),''),nullif(btrim(v_snapshot->>'codigo'),'')),p_source_pantalla_id,v_context,v_snapshot,v_missing,v_status,1,p_execution_id,p_execution_id) returning * into v_rec; v_id:=v_rec.exploration_id;
 else
   if upper(p_task_mode)<>'REMEDIATE_EXISTING' or p_exploration_id is null then raise exception 'LF_EXPLORATION_REMEDIATE_ID_REQUIRED'; end if;
   select * into v_rec from public.lf_input_exploration_records where exploration_id=p_exploration_id for update;
   if not found or v_rec.asset_type<>'REGLA' or v_rec.execution_mode<>'EXPLORATION' or v_rec.governance_status in ('CONSUMED','ARCHIVED') then raise exception 'LF_EXPLORATION_RECORD_NOT_MUTABLE'; end if;
   v_snapshot:=v_rec.partial_payload||p_partial_payload; v_context:=v_rec.source_context||p_source_context; v_revision:=v_rec.revision+1; v_id=v_rec.exploration_id;
   select coalesce(jsonb_agg(k order by ord),'[]'::jsonb) into v_missing from (values (1,'codigo'),(2,'categoria'),(3,'titulo'),(4,'descripcion')) x(ord,k) where nullif(btrim(coalesce(v_snapshot->>k,'')),'') is null;
   update public.lf_input_exploration_records set task_mode='REMEDIATE_EXISTING',target_code=coalesce(nullif(btrim(p_target_code),''),nullif(btrim(v_snapshot->>'codigo'),''),target_code),source_pantalla_id=coalesce(p_source_pantalla_id,source_pantalla_id),source_context=v_context,partial_payload=v_snapshot,missing_fields=v_missing,governance_status=v_status,revision=v_revision,updated_by_execution_id=p_execution_id,updated_at=now() where exploration_id=v_id returning * into v_rec;
 end if;
 insert into public.lf_input_exploration_events(exploration_id,revision,task_mode,delta_payload,snapshot_payload,source_context_delta,governance_status,created_by_execution_id) values(v_id,v_revision,upper(p_task_mode),p_partial_payload,v_snapshot,p_source_context,v_status,p_execution_id);
 return jsonb_build_object('result','EXPLORATION_CAPTURED','exploration_id',v_id,'asset_type','REGLA','task_mode',upper(p_task_mode),'execution_mode','EXPLORATION','governance_status',v_status,'revision',v_revision,'target_code',v_rec.target_code,'source_pantalla_id',v_rec.source_pantalla_id,'partial_payload',v_snapshot,'missing_fields',v_missing,'canonical_write_performed',false,'runtime_activation',false,'promotion',false);
end $$;
revoke all on function public.lf_input_exploration_capture_v1(text,text,text,jsonb,uuid,text,integer,jsonb,boolean) from public,anon,authenticated;
grant execute on function public.lf_input_exploration_capture_v1(text,text,text,jsonb,uuid,text,integer,jsonb,boolean) to service_role;

