CREATE VIEW saly.v_identity_current WITH (security_invoker=true) AS
SELECT p.codigo AS project_code, e.code AS element_code, e.family, e.value_type,
       v.id AS version_id, v.version_number, v.channel_code, v.audience_code,
       v.value_json, v.valid_from, v.valid_to
FROM saly.identity_elements e
JOIN saly.proyecto p ON p.id=e.project_id
JOIN saly.identity_versions v ON v.element_id=e.id
WHERE e.status='ACTIVE' AND v.approval_status='APPROVED'
  AND v.valid_from<=now() AND (v.valid_to IS NULL OR now()<v.valid_to);

CREATE FUNCTION saly.resolve_identity(
  p_project_code text, p_channel_code text, p_audience_code text,
  p_as_of timestamptz DEFAULT now()
)
RETURNS TABLE (
  element_code text, family text, version_id bigint,
  selected_channel text, selected_audience text, value_json jsonb
)
LANGUAGE plpgsql STABLE SECURITY INVOKER
SET search_path=pg_catalog,saly
AS $fn$
DECLARE rec record;
BEGIN
  IF p_project_code IS NULL OR p_channel_code IS NULL OR
     p_audience_code IS NULL OR p_as_of IS NULL THEN
    RAISE EXCEPTION 'INVALID_IDENTITY_CONTEXT';
  END IF;
  FOR rec IN
    WITH candidates AS (
      SELECT e.id AS element_id, e.code AS element_code, e.family AS family_name,
             v.id AS version_id, v.channel_code, v.audience_code, v.value_json,
             CASE
               WHEN v.channel_code=p_channel_code AND v.audience_code=p_audience_code THEN 4
               WHEN v.channel_code=p_channel_code AND v.audience_code='ALL' THEN 3
               WHEN v.channel_code='GLOBAL' AND v.audience_code=p_audience_code THEN 2
               ELSE 1
             END AS precedence
      FROM saly.proyecto p
      JOIN saly.identity_elements e ON e.project_id=p.id
      JOIN saly.identity_versions v ON v.element_id=e.id
      WHERE p.codigo=p_project_code AND e.status='ACTIVE'
        AND v.approval_status='APPROVED' AND v.valid_from<=p_as_of
        AND (v.valid_to IS NULL OR p_as_of<v.valid_to)
        AND v.channel_code IN ('GLOBAL',p_channel_code)
        AND v.audience_code IN ('ALL',p_audience_code)
    ), ranked AS (
      SELECT c.*, row_number() OVER
          (PARTITION BY element_id ORDER BY precedence DESC, version_id DESC) AS rn,
        count(*) OVER (PARTITION BY element_id, precedence) AS same_priority_count
      FROM candidates c
    )
    SELECT * FROM ranked ORDER BY element_code,rn
  LOOP
    IF rec.rn=1 THEN
      IF rec.same_priority_count<>1 THEN
        RAISE EXCEPTION 'AMBIGUOUS_IDENTITY_VERSION: %',rec.element_code;
      END IF;
      element_code:=rec.element_code;
      family:=rec.family_name;
      version_id:=rec.version_id;
      selected_channel:=rec.channel_code;
      selected_audience:=rec.audience_code;
      value_json:=rec.value_json;
      RETURN NEXT;
    END IF;
  END LOOP;
  IF EXISTS (
    SELECT 1 FROM saly.proyecto p
    JOIN saly.identity_elements e ON e.project_id=p.id
    WHERE p.codigo=p_project_code AND e.status='ACTIVE' AND e.is_required
      AND NOT EXISTS (
        SELECT 1 FROM saly.identity_versions v
        WHERE v.element_id=e.id AND v.approval_status='APPROVED'
          AND v.valid_from<=p_as_of
          AND (v.valid_to IS NULL OR p_as_of<v.valid_to)
          AND v.channel_code IN ('GLOBAL',p_channel_code)
          AND v.audience_code IN ('ALL',p_audience_code)
      )
  ) THEN
    RAISE EXCEPTION 'MISSING_REQUIRED_IDENTITY_ELEMENT';
  END IF;
END
$fn$;

DO $postflight$
BEGIN
  IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='saly' AND c.relname IN
      ('identity_elements','identity_versions','brand_assets') AND c.relkind='r')<>3 THEN
    RAISE EXCEPTION 'SALY_IDENTITY_TABLE_POSTFLIGHT_FAILED';
  END IF;
  IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='saly' AND c.relname IN
      ('identity_elements','identity_versions','brand_assets') AND c.relrowsecurity)<>3 THEN
    RAISE EXCEPTION 'SALY_IDENTITY_RLS_POSTFLIGHT_FAILED';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='identity_versions_no_overlap'
      AND conrelid='saly.identity_versions'::regclass)
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='brand_assets_no_overlap'
      AND conrelid='saly.brand_assets'::regclass) THEN
    RAISE EXCEPTION 'SALY_IDENTITY_TEMPORAL_POSTFLIGHT_FAILED';
  END IF;
END
$postflight$;

