CREATE TABLE saly.identity_elements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES saly.proyecto(id) ON DELETE RESTRICT,
  code text NOT NULL,
  family text NOT NULL CHECK (family IN
    ('COLOR','TYPOGRAPHY','VOICE','LANGUAGE','PATTERN','MOTION','SPACING','LAYOUT','RULE')),
  value_type text NOT NULL CHECK (value_type IN
    ('COLOR','TEXT','NUMBER','BOOLEAN','JSON','ASSET_REF')),
  name text NOT NULL,
  description text,
  is_required boolean NOT NULL DEFAULT false,
  is_protected boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','ACTIVE','DEPRECATED')),
  decision_id bigint REFERENCES saly.decisiones(id) ON DELETE RESTRICT,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(metadata)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT identity_elements_code_format_chk
    CHECK (code ~ '^[a-z][a-z0-9_.-]{1,127}$'),
  CONSTRAINT identity_elements_project_code_uk UNIQUE (project_id,code)
);

CREATE TABLE saly.identity_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  element_id bigint NOT NULL REFERENCES saly.identity_elements(id) ON DELETE RESTRICT,
  version_number integer NOT NULL CHECK (version_number > 0),
  channel_code text NOT NULL DEFAULT 'GLOBAL',
  audience_code text NOT NULL DEFAULT 'ALL',
  value_json jsonb NOT NULL,
  approval_status text NOT NULL DEFAULT 'DRAFT'
    CHECK (approval_status IN ('DRAFT','CANDIDATE','APPROVED','REVOKED')),
  valid_from timestamptz,
  valid_to timestamptz,
  decision_id bigint REFERENCES saly.decisiones(id) ON DELETE RESTRICT,
  approval_reference text,
  change_reason text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(metadata)='object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT identity_versions_context_chk CHECK (
    channel_code ~ '^[A-Z][A-Z0-9_]{1,31}$'
    AND audience_code ~ '^[A-Z][A-Z0-9_]{1,31}$'),
  CONSTRAINT identity_versions_value_chk CHECK (
    jsonb_typeof(value_json)='object' AND value_json ? 'value'),
  CONSTRAINT identity_versions_dates_chk CHECK (
    valid_to IS NULL OR (valid_from IS NOT NULL AND valid_to > valid_from)),
  CONSTRAINT identity_versions_approval_chk CHECK (
    approval_status <> 'APPROVED' OR
    (valid_from IS NOT NULL AND
     (decision_id IS NOT NULL OR nullif(btrim(approval_reference),'') IS NOT NULL))),
  CONSTRAINT identity_versions_number_uk UNIQUE
    (element_id, channel_code, audience_code, version_number)
);

CREATE UNIQUE INDEX identity_versions_open_approved_uk
ON saly.identity_versions(element_id,channel_code,audience_code)
