-- INV-9.5a — external repository/Edge baseline synchronization primitives v1.
-- Git-first / EXACT_VERSION_SOURCE_FIRST.
-- This migration is source-only in this PR. Do not apply before independent audit.
--
-- Separation of responsibility:
--   baseline sync mutates object identity/baseline only;
--   inventory.fn_apply_external_currentness_observation_v1 remains the sole writer
--   of currentness/currentness_source/observed_at/observed_main_sha/source_traceability_state.
--
-- Approval:
--   large/risky deltas are created as REQUIRES_APPROVAL and are approved by
--   workflow_dispatch using the exact sync_key. Approval records GitHub actor/run
--   identity in lf_eventos before finalize.
--
-- Storage:
--   thresholds and capacity are governed by lf_ops.reglas. Missing/invalid config
--   fails closed. Capacity is checked at begin and again immediately before finalize.

do $preflight$
begin
  if exists (
    select 1 from lf_ops.reglas
    where codigo='EXTERNAL-BASELINE-SYNC-POLICY-001'
  ) then
    raise exception 'INV_9_5A_POLICY_ALREADY_EXISTS';
  end if;

  if to_regclass('inventory.baseline_sync_runs') is not null
     or to_regclass('inventory.baseline_sync_items') is not null then
    raise exception 'INV_9_5A_SYNC_TABLE_ALREADY_EXISTS';
  end if;

  if pg_catalog.to_regprocedure('public.lf_external_baseline_sync_policy_v1()') is not null
     or pg_catalog.to_regprocedure('inventory.fn_begin_external_baseline_sync_v1(text,text,integer,integer,integer,integer,integer,integer,integer)') is not null
     or pg_catalog.to_regprocedure('inventory.fn_stage_external_baseline_batch_v1(text,integer,jsonb)') is not null
     or pg_catalog.to_regprocedure('inventory.fn_approve_external_baseline_sync_v1(text,text,bigint,text)') is not null
     or pg_catalog.to_regprocedure('inventory.fn_finalize_external_baseline_sync_v1(text)') is not null then
    raise exception 'INV_9_5A_FUNCTION_ALREADY_EXISTS';
  end if;

  if pg_catalog.to_regprocedure(
    'private.fn_lf_event_contract_assessment_v3(text,text,text,text,jsonb,text)'
  ) is null then
    raise exception 'INV_9_5A_EVENT_VALIDATOR_MISSING';
  end if;
end
