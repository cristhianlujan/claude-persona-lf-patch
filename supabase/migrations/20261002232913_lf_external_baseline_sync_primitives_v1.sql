create function public.lf_external_baseline_sync_policy_v1()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_count integer;
  v_rule record;
  v_cfg jsonb;
begin
  select count(*) into v_count
  from lf_ops.reglas
  where codigo='EXTERNAL-BASELINE-SYNC-POLICY-001';

  if v_count<>1 then
    raise exception 'BASELINE_POLICY_CARDINALITY_MISMATCH expected=1 actual=%',v_count;
  end if;

  select id,codigo,estado,valor_config,updated_at
  into v_rule
  from lf_ops.reglas
  where codigo='EXTERNAL-BASELINE-SYNC-POLICY-001';

  if v_rule.estado<>'VIGENTE' then
    raise exception 'BASELINE_POLICY_NOT_VIGENTE actual=%',v_rule.estado;
  end if;

  v_cfg := v_rule.valor_config;

  if v_cfg is null
     or jsonb_typeof(v_cfg)<>'object'
     or v_cfg->>'schema_version'<>'lf-external-baseline-sync-policy/v1'
     or coalesce((v_cfg->>'fail_closed')::boolean,false) is not true
     or coalesce((v_cfg->>'batch_size')::integer,0) not between 1 and 500
     or coalesce((v_cfg->>'missing_confirmation_runs')::integer,0)<>2
     or coalesce((v_cfg->>'runtime_without_source_requires_approval')::boolean,false) is not true
     or jsonb_typeof(v_cfg->'allowed_approval_actors')<>'array'
     or jsonb_array_length(v_cfg->'allowed_approval_actors')<1
     or coalesce((v_cfg#>>'{repo,max_changes_abs}')::integer,-1)<0
     or coalesce((v_cfg#>>'{repo,max_change_pct}')::numeric,-1)<0
     or coalesce((v_cfg#>>'{repo,max_change_pct}')::numeric,2)>1
     or coalesce((v_cfg#>>'{repo,max_deactivations_abs}')::integer,-1)<0
     or coalesce((v_cfg#>>'{repo,max_deactivation_pct}')::numeric,-1)<0
     or coalesce((v_cfg#>>'{repo,max_deactivation_pct}')::numeric,2)>1
     or coalesce((v_cfg#>>'{edge,max_changes_abs}')::integer,-1)<0
     or coalesce((v_cfg#>>'{edge,max_deactivations_abs}')::integer,-1)<0
     or coalesce((v_cfg#>>'{storage,db_capacity_bytes}')::bigint,0)<=0
     or coalesce((v_cfg#>>'{storage,safety_margin_bytes}')::bigint,0)<=0
     or coalesce((v_cfg#>>'{storage,repo_new_projected_bytes}')::bigint,0)<=0
     or coalesce((v_cfg#>>'{storage,edge_new_projected_bytes}')::bigint,0)<=0
     or coalesce((v_cfg#>>'{storage,staging_item_projected_bytes}')::bigint,0)<=0
     or (v_cfg#>>'{storage,safety_margin_bytes}')::bigint >=
        (v_cfg#>>'{storage,db_capacity_bytes}')::bigint
     or exists (
       select 1
       from jsonb_array_elements_text(v_cfg->'allowed_approval_actors') a(value)
       where btrim(value)=''
     ) then
    raise exception 'BASELINE_POLICY_INVALID';
  end if;

  return jsonb_build_object(
    'schema_version','lf-external-baseline-sync-policy-reader/v1',
    'rule_id',v_rule.id,
    'codigo',v_rule.codigo,
    'estado',v_rule.estado,
    'valor_config',v_cfg,
    'updated_at',v_rule.updated_at,
    'observed_at',clock_timestamp()
  );
end
$function$;

