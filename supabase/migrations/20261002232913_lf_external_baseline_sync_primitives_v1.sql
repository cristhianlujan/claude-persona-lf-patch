create table inventory.baseline_sync_runs(
  sync_id bigint generated by default as identity primary key,
  sync_key text not null unique,
  observed_main_sha text not null,
  report_sha256 text not null,
  status text not null,
  expected_repo_new integer not null,
  expected_repo_stale integer not null,
  expected_repo_missing integer not null,
  expected_edge_new integer not null,
  expected_edge_stale integer not null,
  expected_edge_missing integer not null,
  runtime_without_source_count integer not null default 0,
  expected_item_count integer not null,
  staged_item_count integer not null default 0,
  requires_approval boolean not null,
  approval_reasons jsonb not null default '[]'::jsonb,
  config_rule_id integer not null,
  config_updated_at timestamptz not null,
  config_sha256 text not null,
  config_snapshot jsonb not null,
  db_size_at_begin bigint not null,
  projected_baseline_growth_bytes bigint not null,
  projected_staging_growth_bytes bigint not null,
  created_at timestamptz not null default clock_timestamp(),
  approved_at timestamptz,
  approved_by_actor text,
  approval_github_run_id bigint,
  approval_workflow_sha text,
  approval_event_id bigint,
  finalized_at timestamptz,
  snapshot_id bigint,
  constraint baseline_sync_runs_key_ck check (sync_key ~ '^[0-9a-f]{64}$'),
  constraint baseline_sync_runs_main_sha_ck check (observed_main_sha ~ '^[0-9a-f]{40}$'),
  constraint baseline_sync_runs_report_sha_ck check (report_sha256 ~ '^[0-9a-f]{64}$'),
  constraint baseline_sync_runs_config_sha_ck check (config_sha256 ~ '^[0-9a-f]{64}$'),
  constraint baseline_sync_runs_status_ck check (
    status in ('STAGING','REQUIRES_APPROVAL','APPROVED','COMPLETED')
  ),
  constraint baseline_sync_runs_counts_ck check (
    expected_repo_new>=0 and expected_repo_stale>=0 and expected_repo_missing>=0
    and expected_edge_new>=0 and expected_edge_stale>=0 and expected_edge_missing>=0
    and runtime_without_source_count>=0 and expected_item_count>0
    and staged_item_count>=0 and staged_item_count<=expected_item_count
  ),
  constraint baseline_sync_runs_expected_total_ck check (
    expected_item_count =
      expected_repo_new+expected_repo_stale+expected_repo_missing+
      expected_edge_new+expected_edge_stale+expected_edge_missing
  ),
  constraint baseline_sync_runs_projection_ck check (
    db_size_at_begin>=0
    and projected_baseline_growth_bytes>=0
    and projected_staging_growth_bytes>=0
  )
);

create index baseline_sync_runs_status_idx
  on inventory.baseline_sync_runs(status,created_at);

