  source_kind text not null,
  object_key text not null,
  state text not null,
  definition_sha256 text,
  source_version text,
  git_blob text,
  verify_jwt boolean,
  source_state text,
  byte_size bigint,
  extension text,
  batch_no integer not null,
  created_at timestamptz not null default clock_timestamp(),
  primary key(sync_id,source_kind,object_key),
  constraint baseline_sync_items_source_ck check (source_kind in ('REPO','EDGE')),
  constraint baseline_sync_items_state_ck check (state in ('NEW','STALE','MISSING')),
  constraint baseline_sync_items_batch_ck check (batch_no>0),
  constraint baseline_sync_items_bytes_ck check (byte_size is null or byte_size>=0)
);

create index baseline_sync_items_batch_idx
  on inventory.baseline_sync_items(sync_id,batch_no);

