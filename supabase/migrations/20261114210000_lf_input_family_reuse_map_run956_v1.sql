CREATE FUNCTION public.lf_input_family_reuse_before_propose_v1(
 p_pantalla_id integer,p_family_code text,p_run_id bigint DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog','public','programacion','lf_ops'
AS $lookup$
DECLARE v record; v_live_valid boolean;
BEGIN
 SELECT m.*,a.coverage_status AS current_source_coverage INTO v
 FROM programacion.input_family_reuse_map_v1 m
 JOIN programacion.input_family_assessments a ON a.id=m.assessment_id
 WHERE m.pantalla_id=p_pantalla_id AND m.family_code=p_family_code
 AND (p_run_id IS NULL OR m.source_run_id=p_run_id)
 ORDER BY m.source_run_id DESC LIMIT 1;
 IF NOT FOUND THEN
  RETURN jsonb_build_object('status','NOT_MAPPED_REVIEW_SOURCE',
   'continuation_allowed',true,'automatic_rule_creation',false,
   'source_discovery_required',true,'closure_verified',false);
 END IF;
 -- A new run supersedes this evidentiary map; never silently reuse old 956 mapping.
 IF EXISTS(SELECT 1 FROM programacion.input_readiness_runs newer
           WHERE newer.pantalla_id=v.pantalla_id AND newer.id>v.source_run_id) THEN
   RETURN jsonb_build_object('status','STALE_IG_RUN_RECURATE',
     'source_run_id',v.source_run_id,'screen_id',v.pantalla_id,'family',v.family_code,
     'continuation_allowed',true,'automatic_rule_creation',false,
     'closure_verified',false,'policy_link_written',false,
     'next_action','RECURATE_AND_REBUILD_FAMILY_REUSE_MAPPING');
 END IF;
 v_live_valid:=CASE
  WHEN v.resolution_path='HEREDAR' THEN EXISTS(
    SELECT 1 FROM lf_ops.reglas r WHERE r.id=v.transversal_regla_id
    AND r.es_transversal AND r.estado='VIGENTE')
  WHEN v.resolution_path='ATAR_POLITICA' THEN CASE v.policy_kind
    WHEN 'SECURITY' THEN EXISTS (SELECT 1 FROM lf_ops.politicas_seguridad p
       WHERE p.security_policy_id=v.policy_numeric_id AND p.policy_code=v.policy_code
       AND p.status=v.policy_catalog_status)
    WHEN 'RATE_LIMIT' THEN EXISTS (SELECT 1 FROM lf_ops.politicas_rate_limit p
       WHERE p.rate_limit_policy_id=v.policy_numeric_id AND p.policy_code=v.policy_code
       AND p.status=v.policy_catalog_status)
    WHEN 'SESSION' THEN EXISTS (SELECT 1 FROM lf_ops.politicas_sesion p
       WHERE p.session_policy_id=v.policy_numeric_id AND p.policy_code=v.policy_code
       AND p.status=v.policy_catalog_status)
    WHEN 'TIMEOUT' THEN EXISTS (SELECT 1 FROM lf_ops.politicas_timeout p
       WHERE p.timeout_policy_id=v.policy_numeric_id AND p.policy_code=v.policy_code
       AND p.status=v.policy_catalog_status)
    ELSE false END
  ELSE true END;
 RETURN jsonb_build_object(
  'status',CASE WHEN v_live_valid THEN 'REUSE_PROPOSAL_WITH_FINDINGS' ELSE 'SOURCE_DRIFT_REVIEW' END,
  'source_run_id',v.source_run_id,'screen_id',v.pantalla_id,'family',v.family_code,
  'original_coverage_status',v.current_source_coverage,
  'route',v.resolution_path,'transversal_rule_id',v.transversal_regla_id,
  'policy_kind',v.policy_kind,'policy_code',v.policy_code,
  'policy_status',v.policy_catalog_status,
  'policy_screen_row_proposal',v.proposed_pantallas_politicas_row,
  'policy_rule_ids_proposal',v.proposed_pantallas_politicas_reglas_ids,
  'candidate_cases',v.candidate_cases,
  'evidence',v.source_refs,'source_curator_sha256',v.source_curator_sha256,
  'blocker_code',v.blocker_code,'residual_finding',v.residual_finding,
  'technical_dependency',v.technical_dependency,
  'continuation_allowed',true,'automatic_rule_creation',false,
  'closure_verified',false,'policy_link_written',false,
  'owner_decision_verified',false,'next_action','PROFILE_REVIEW_AND_CURATOR_EVIDENCE_READBACK'
 );
END $lookup$;
