-- LF screen composition v1: regions per layout and element placement per screen.
-- Composition only: region, order, alignment, visibility and token references.
-- No pixel columns: sizes and spacing resolve through lf_design.spacing_tokens
-- (b2b_auth_login_layout: form_max_width_policy=TOKEN_SCALE_ONLY;
--  responsive_architecture=SINGLE_LAYOUT_CONTAINER_QUERIES).
BEGIN;

-- 1. Regions of a layout component and their placement per breakpoint.
CREATE TABLE lf_design.layout_regions (
  layout_region_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  layout_component_token_id bigint NOT NULL
    REFERENCES lf_design.component_tokens(component_token_id) ON DELETE RESTRICT,
  region_code text NOT NULL CHECK (region_code ~ '^[A-Z][A-Z0-9_]{1,40}$'),
  region_order integer NOT NULL CHECK (region_order > 0),
  placement_by_breakpoint jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(placement_by_breakpoint) = 'object'),
  max_width_token_id bigint
    REFERENCES lf_design.spacing_tokens(spacing_token_id) ON DELETE RESTRICT,
  gap_token_id bigint
    REFERENCES lf_design.spacing_tokens(spacing_token_id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'CANDIDATO'
    CHECK (status IN ('CANDIDATO', 'CANDIDATO_VISUAL', 'VIGENTE', 'DEPRECATED')),
  source_refs jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(source_refs) = 'array'),
  source_decision_id text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (layout_component_token_id, region_code),
  UNIQUE (layout_component_token_id, region_order)
);

COMMENT ON TABLE lf_design.layout_regions IS
  'Regiones de un componente de layout (HEADER, MAIN, FOOTER, DECORATIVE...) y su ubicación por breakpoint. Claves de placement_by_breakpoint = lf_design.responsive_tokens.token_name. Sin píxeles: anchos y separaciones solo por spacing_tokens.';

-- placement values come from a closed catalogue; keys must be existing responsive tokens.
CREATE FUNCTION lf_design.layout_regions_placement_guard_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, lf_design
AS $$
DECLARE
  k text;
  v text;
BEGIN
  FOR k, v IN SELECT key, value FROM jsonb_each_text(NEW.placement_by_breakpoint) LOOP
    IF NOT EXISTS (SELECT 1 FROM lf_design.responsive_tokens r WHERE r.token_name = k) THEN
      RAISE EXCEPTION 'LAYOUT_REGION_UNKNOWN_BREAKPOINT:%', k;
    END IF;
    IF v NOT IN ('LEFT_COLUMN', 'RIGHT_COLUMN', 'CENTER', 'STACK', 'TOP', 'BOTTOM', 'BACKGROUND', 'HIDDEN') THEN
      RAISE EXCEPTION 'LAYOUT_REGION_INVALID_PLACEMENT:%:%', k, v;
    END IF;
  END LOOP;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER layout_regions_placement_guard_v1
  BEFORE INSERT OR UPDATE ON lf_design.layout_regions
  FOR EACH ROW EXECUTE FUNCTION lf_design.layout_regions_placement_guard_v1();

-- 2. Placement of each screen element inside a region (base row + optional per-variant override).
CREATE TABLE lf_ops.pantalla_elemento_layouts (
  element_layout_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  element_id bigint NOT NULL
    REFERENCES lf_ops.pantalla_elementos(element_id) ON DELETE RESTRICT,
  variant_id bigint
    REFERENCES lf_ops.pantalla_variantes(variant_id) ON DELETE RESTRICT,
  composition_role text NOT NULL DEFAULT 'PLACED'
    CHECK (composition_role IN ('PLACED', 'CONTAINER', 'EMBEDDED', 'NON_VISUAL')),
  layout_region_id bigint
    REFERENCES lf_design.layout_regions(layout_region_id) ON DELETE RESTRICT,
  order_in_region integer CHECK (order_in_region > 0),
  alignment text NOT NULL DEFAULT 'START'
    CHECK (alignment IN ('START', 'CENTER', 'END', 'STRETCH')),
  width_mode text NOT NULL DEFAULT 'FILL_REGION'
    CHECK (width_mode IN ('FILL_REGION', 'CONTENT', 'TOKEN')),
  width_token_id bigint
    REFERENCES lf_design.spacing_tokens(spacing_token_id) ON DELETE RESTRICT,
  spacing_before_token_id bigint
    REFERENCES lf_design.spacing_tokens(spacing_token_id) ON DELETE RESTRICT,
  visible boolean NOT NULL DEFAULT true,
  status text NOT NULL DEFAULT 'CANDIDATO'
    CHECK (status IN ('CANDIDATO', 'CANDIDATO_VISUAL', 'VIGENTE', 'DEPRECATED')),
  source_refs jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(source_refs) = 'array'),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((width_mode = 'TOKEN') = (width_token_id IS NOT NULL)),
  -- PLACED elements live in a region with an order; CONTAINER (frame/layout),
  -- EMBEDDED (rendered inside another element) and NON_VISUAL elements do not.
  CHECK ((composition_role = 'PLACED') = (layout_region_id IS NOT NULL AND order_in_region IS NOT NULL)),
  CHECK (composition_role <> 'NON_VISUAL' OR NOT visible)
);

COMMENT ON TABLE lf_ops.pantalla_elemento_layouts IS
  'Composición de cada elemento de pantalla: rol de composición, región, orden, alineación, ancho por token y visibilidad. Fila base con variant_id NULL; filas por variante solo para lo que cambia en ese breakpoint. Todo elemento obligatorio declara su fila base, también los contenedores (CONTAINER), los que se renderizan dentro de otro (EMBEDDED) y los no visuales (NON_VISUAL). Sin columnas de píxeles.';

-- One base row per element, one override per element and variant.
CREATE UNIQUE INDEX pantalla_elemento_layouts_base_uk
  ON lf_ops.pantalla_elemento_layouts (element_id) WHERE variant_id IS NULL;
CREATE UNIQUE INDEX pantalla_elemento_layouts_variant_uk
  ON lf_ops.pantalla_elemento_layouts (element_id, variant_id) WHERE variant_id IS NOT NULL;
CREATE INDEX pantalla_elemento_layouts_region_idx
  ON lf_ops.pantalla_elemento_layouts (layout_region_id) WHERE layout_region_id IS NOT NULL;

-- Integrity: a variant override must belong to the element's screen, and the
-- region must belong to that screen's layout component.
CREATE FUNCTION lf_ops.pantalla_elemento_layouts_guard_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, lf_ops, lf_design
AS $$
DECLARE
  v_pantalla integer;
BEGIN
  SELECT pe.pantalla_id INTO v_pantalla FROM lf_ops.pantalla_elementos pe WHERE pe.element_id = NEW.element_id;
  IF NEW.variant_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM lf_ops.pantalla_variantes pv
    WHERE pv.variant_id = NEW.variant_id AND pv.pantalla_id = v_pantalla) THEN
    RAISE EXCEPTION 'ELEMENT_LAYOUT_VARIANT_OTHER_SCREEN:%:%', NEW.element_id, NEW.variant_id;
  END IF;
  IF NEW.layout_region_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM lf_design.layout_regions lr
    JOIN lf_ops.pantalla_variantes pv ON pv.layout_component_token_id = lr.layout_component_token_id
    WHERE lr.layout_region_id = NEW.layout_region_id AND pv.pantalla_id = v_pantalla) THEN
    RAISE EXCEPTION 'ELEMENT_LAYOUT_REGION_NOT_IN_SCREEN_LAYOUT:%:%', NEW.element_id, NEW.layout_region_id;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER pantalla_elemento_layouts_guard_v1
  BEFORE INSERT OR UPDATE ON lf_ops.pantalla_elemento_layouts
  FOR EACH ROW EXECUTE FUNCTION lf_ops.pantalla_elemento_layouts_guard_v1();

-- 3. Effective composition per screen and variant (override wins over base row).
CREATE VIEW lf_ops.v_pantalla_composicion
WITH (security_invoker = true) AS
SELECT
  pe.pantalla_id,
  pv.variant_id,
  pv.variant_code,
  pv.responsive_token_name,
  eff.composition_role,
  lr.region_code,
  lr.region_order,
  lr.placement_by_breakpoint ->> pv.responsive_token_name AS region_placement,
  rw.token_name AS region_max_width_token,
  rg.token_name AS region_gap_token,
  pe.element_id,
  pe.element_code,
  pe.element_role,
  pe.component_token_id,
  eff.order_in_region,
  eff.alignment,
  eff.width_mode,
  ew.token_name AS width_token,
  es.token_name AS spacing_before_token,
  eff.visible,
  (eff.variant_id IS NOT NULL) AS is_variant_override,
  eff.status AS layout_status,
  eff.source_refs AS layout_source_refs
FROM lf_ops.pantalla_elementos pe
JOIN lf_ops.pantalla_variantes pv ON pv.pantalla_id = pe.pantalla_id
JOIN LATERAL (
  SELECT l.*
  FROM lf_ops.pantalla_elemento_layouts l
  WHERE l.element_id = pe.element_id
    AND (l.variant_id = pv.variant_id OR l.variant_id IS NULL)
    AND l.status <> 'DEPRECATED'
  ORDER BY (l.variant_id IS NULL)
  LIMIT 1
) eff ON true
LEFT JOIN lf_design.layout_regions lr ON lr.layout_region_id = eff.layout_region_id
LEFT JOIN lf_design.spacing_tokens rw ON rw.spacing_token_id = lr.max_width_token_id
LEFT JOIN lf_design.spacing_tokens rg ON rg.spacing_token_id = lr.gap_token_id
LEFT JOIN lf_design.spacing_tokens ew ON ew.spacing_token_id = eff.width_token_id
LEFT JOIN lf_design.spacing_tokens es ON es.spacing_token_id = eff.spacing_before_token_id
WHERE pe.status <> 'DEPRECATED';

COMMENT ON VIEW lf_ops.v_pantalla_composicion IS
  'Composición efectiva por pantalla y variante: la fila de la variante prevalece sobre la base. Solo lectura, para Input Governance y la ruta de Programación.';

-- 4. Completeness check: required elements without composition.
CREATE VIEW lf_ops.v_pantalla_composicion_gaps
WITH (security_invoker = true) AS
SELECT pe.pantalla_id, pe.element_id, pe.element_code, pe.element_role,
       'ELEMENT_LAYOUT_MISSING'::text AS gap_code
FROM lf_ops.pantalla_elementos pe
WHERE pe.required_for_implementation
  AND pe.status <> 'DEPRECATED'
  AND NOT EXISTS (
    SELECT 1 FROM lf_ops.pantalla_elemento_layouts l
    WHERE l.element_id = pe.element_id AND l.variant_id IS NULL AND l.status <> 'DEPRECATED');

COMMENT ON VIEW lf_ops.v_pantalla_composicion_gaps IS
  'Elementos obligatorios sin fila base de composición. Una pantalla está lista para composición cuando esta vista no devuelve filas para ella.';

-- 5. Access: same posture as lf_ops.pantalla_elementos and lf_design.spacing_tokens.
ALTER TABLE lf_design.layout_regions ENABLE ROW LEVEL SECURITY;
ALTER TABLE lf_ops.pantalla_elemento_layouts ENABLE ROW LEVEL SECURITY;
CREATE POLICY deny_direct_client_access ON lf_design.layout_regions
  AS PERMISSIVE FOR ALL TO anon, authenticated USING (false) WITH CHECK (false);
CREATE POLICY deny_direct_client_access ON lf_ops.pantalla_elemento_layouts
  AS PERMISSIVE FOR ALL TO anon, authenticated USING (false) WITH CHECK (false);
REVOKE ALL ON lf_design.layout_regions, lf_ops.pantalla_elemento_layouts FROM anon, authenticated;
REVOKE ALL ON lf_ops.v_pantalla_composicion, lf_ops.v_pantalla_composicion_gaps FROM anon, authenticated;
REVOKE ALL ON FUNCTION lf_design.layout_regions_placement_guard_v1() FROM PUBLIC;
REVOKE ALL ON FUNCTION lf_ops.pantalla_elemento_layouts_guard_v1() FROM PUBLIC;

COMMIT;
