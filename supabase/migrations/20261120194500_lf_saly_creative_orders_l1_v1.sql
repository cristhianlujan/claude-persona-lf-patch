-- Transactional selftest with intentional subtransaction rollback; no sample orders persist.
DO $selftest$
DECLARE v_project bigint; v_order bigint; v_a bigint; v_b bigint;
 v_arun bigint; v_brun bigint; v_blocked boolean; v_sha text:=repeat('a',64);
BEGIN
 SELECT id INTO STRICT v_project FROM saly.proyecto WHERE codigo='SALY-001';
 BEGIN
   INSERT INTO saly.creative_orders(project_id,code,request_key,title,requested_by,status)
   VALUES(v_project,'SALY_TEST_L1','SALY_TEST_L1','Transactional selftest','SELFTEST','EN_PROCESO')
   RETURNING id INTO v_order;
   INSERT INTO saly.creative_order_items(order_id,code,ordinal,kind,title,status)
   VALUES(v_order,'SCREEN_A',1,'SCREEN','A','EN_QA') RETURNING id INTO v_a;
   INSERT INTO saly.creative_order_items(order_id,code,ordinal,kind,title,status)
   VALUES(v_order,'SCREEN_B',2,'SCREEN','B','EN_QA') RETURNING id INTO v_b;
   INSERT INTO saly.creative_item_dependencies(order_id,item_id,depends_on_item_id)
   VALUES(v_order,v_b,v_a);

   v_blocked:=false;
   BEGIN
     INSERT INTO saly.creative_item_dependencies(order_id,item_id,depends_on_item_id)
     VALUES(v_order,v_a,v_b);
   EXCEPTION WHEN raise_exception THEN
     IF SQLERRM='CREATIVE_DEPENDENCY_CYCLE' THEN v_blocked:=true; ELSE RAISE; END IF;
   END;
   IF NOT v_blocked THEN RAISE EXCEPTION 'SALY_L1_CYCLE_TEST_FAILED'; END IF;

   v_blocked:=false;
   BEGIN
     UPDATE saly.creative_orders SET status='COMPLETADO',completed_at=now() WHERE id=v_order;
   EXCEPTION WHEN raise_exception THEN
     IF SQLERRM='CREATIVE_ORDER_CLOSURE_WITH_INCOMPLETE_DETAILS' THEN v_blocked:=true; ELSE RAISE; END IF;
   END;
   IF NOT v_blocked THEN RAISE EXCEPTION 'SALY_L1_CLOSURE_TEST_FAILED'; END IF;

   INSERT INTO saly.creative_runs(order_id,item_id,attempt_number,idempotency_key,state)
   VALUES(v_order,v_a,1,'run-a','EN_COLA') RETURNING id INTO v_arun;
   UPDATE saly.creative_runs SET state='EJECUTANDO',worker_ref='producer-a',
     started_at=now() WHERE id=v_arun;
   v_blocked:=false;
   BEGIN
     UPDATE saly.creative_runs SET state='EXITOSO',finished_at=now() WHERE id=v_arun;
   EXCEPTION WHEN check_violation THEN v_blocked:=true; END;
   IF NOT v_blocked THEN RAISE EXCEPTION 'SALY_L1_EMPTY_EVIDENCE_TEST_FAILED'; END IF;
   UPDATE saly.creative_runs SET state='EXITOSO',finished_at=now(),
     input_snapshot=jsonb_build_object('identity_versions',jsonb_build_array(7,8),
       'source_refs',jsonb_build_array('TEST_SOURCE'),'screen_spec','TEST_SPEC'),
     output_evidence=jsonb_build_object('artifact_ref','TEST_ARTIFACT',
       'sha256',v_sha,'worker_receipt','TEST_WORKER')
   WHERE id=v_arun;
   INSERT INTO saly.creative_runs(order_id,item_id,attempt_number,idempotency_key,state)
   VALUES(v_order,v_b,1,'run-b','EN_COLA') RETURNING id INTO v_brun;
   UPDATE saly.creative_runs SET state='EJECUTANDO',worker_ref='producer-b',
     started_at=now() WHERE id=v_brun;
   UPDATE saly.creative_runs SET state='EXITOSO',finished_at=now(),
     input_snapshot=jsonb_build_object('identity_versions',jsonb_build_array(7,8),
       'source_refs',jsonb_build_array('TEST_SOURCE'),'screen_spec','TEST_SPEC'),
     output_evidence=jsonb_build_object('artifact_ref','TEST_ARTIFACT_B',
       'sha256',v_sha,'worker_receipt','TEST_WORKER_B')
   WHERE id=v_brun;

   v_blocked:=false;
   BEGIN
     UPDATE saly.creative_order_items SET status='APROBADO',approved_at=now(),
       approved_by='qa-reviewer',qa_receipt=jsonb_build_object(
          'run_id',v_brun,'verdict','PASS','reviewer_ref','qa-reviewer')
     WHERE id=v_b;
   EXCEPTION WHEN raise_exception THEN
     IF SQLERRM='CREATIVE_DEPENDENCY_NOT_APPROVED' THEN v_blocked:=true; ELSE RAISE; END IF;
   END;
   IF NOT v_blocked THEN RAISE EXCEPTION 'SALY_L1_DEPENDENCY_TEST_FAILED'; END IF;

   v_blocked:=false;
   BEGIN
     UPDATE saly.creative_order_items SET status='APROBADO',approved_at=now(),
       approved_by='producer-a',qa_receipt=jsonb_build_object(
          'run_id',v_arun,'verdict','PASS','reviewer_ref','producer-a') WHERE id=v_a;
   EXCEPTION WHEN raise_exception THEN
     IF SQLERRM='CREATIVE_QA_NOT_INDEPENDENT_OR_RUN_MISSING' THEN v_blocked:=true; ELSE RAISE; END IF;
   END;
   IF NOT v_blocked THEN RAISE EXCEPTION 'SALY_L1_SELF_APPROVAL_TEST_FAILED'; END IF;

   UPDATE saly.creative_order_items SET status='APROBADO',approved_at=now(),
     approved_by='qa-reviewer',qa_receipt=jsonb_build_object(
       'run_id',v_arun,'verdict','PASS','reviewer_ref','qa-reviewer') WHERE id=v_a;
   UPDATE saly.creative_order_items SET status='APROBADO',approved_at=now(),
     approved_by='qa-reviewer',qa_receipt=jsonb_build_object(
       'run_id',v_brun,'verdict','PASS','reviewer_ref','qa-reviewer') WHERE id=v_b;
   UPDATE saly.creative_orders SET status='COMPLETADO',completed_at=now() WHERE id=v_order;

   v_blocked:=false;
   BEGIN
     UPDATE saly.creative_runs SET error_code='MUTATED' WHERE id=v_arun;
   EXCEPTION WHEN raise_exception THEN
     IF SQLERRM='CREATIVE_TERMINAL_RUN_IMMUTABLE' THEN v_blocked:=true; ELSE RAISE; END IF;
   END;
   IF NOT v_blocked THEN RAISE EXCEPTION 'SALY_L1_RUN_IMMUTABILITY_FAILED'; END IF;
   RAISE EXCEPTION 'SALY_CREATIVE_L1_SELFTEST_ROLLBACK_PASS';
 EXCEPTION WHEN raise_exception THEN
   IF SQLERRM<>'SALY_CREATIVE_L1_SELFTEST_ROLLBACK_PASS' THEN RAISE; END IF;
 END;
 IF EXISTS(SELECT 1 FROM saly.creative_orders WHERE code='SALY_TEST_L1')
 THEN RAISE EXCEPTION 'SALY_L1_TEST_DATA_PERSISTED'; END IF;
END $selftest$;

DO $postflight$
BEGIN
 IF (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
  WHERE n.nspname='saly'
   AND c.relname IN ('creative_orders','creative_order_items','creative_item_dependencies','creative_runs')
   AND c.relkind='r' AND c.relrowsecurity AND c.relforcerowsecurity)<>4
 THEN RAISE EXCEPTION 'SALY_CREATIVE_L1_RLS_POSTFLIGHT_FAILED'; END IF;
 IF (SELECT count(*) FROM saly.creative_orders)<>0
  OR (SELECT count(*) FROM saly.creative_order_items)<>0
  OR (SELECT count(*) FROM saly.creative_item_dependencies)<>0
  OR (SELECT count(*) FROM saly.creative_runs)<>0
 THEN RAISE EXCEPTION 'SALY_CREATIVE_L1_EMPTY_BASELINE_FAILED'; END IF;
END $postflight$;
COMMIT;
