begin;

alter table private.lf_repository_governance_bundle_v4
  drop constraint lf_repository_governance_bundle_v4_pkey;

alter table private.lf_repository_governance_bundle_v4
  add column revision_id bigint generated by default as identity;

alter table private.lf_repository_governance_bundle_v4
  add constraint lf_repository_governance_bundle_v4_pkey
  primary key (path, revision_id);

create or replace function public.get_lf_repository_governance_bundle_v4()
returns table(path text, expected_sha256 text, expected_git_blob text, control_kind text)
language sql
stable
security definer
set search_path='pg_catalog','private'
as $function$
  select distinct on (b.path)
         b.path,b.expected_sha256,b.expected_git_blob,b.control_kind
  from private.lf_repository_governance_bundle_v4 b
  where b.active
  order by b.path,b.revision_id desc;
$function$;

insert into private.lf_repository_governance_bundle_v4(
  path,expected_sha256,expected_git_blob,control_kind,active,
  approved_commit_sha,approved_by_execution_id
