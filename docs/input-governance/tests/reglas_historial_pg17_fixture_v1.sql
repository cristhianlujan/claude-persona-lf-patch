-- Modelo PG17 desechable de lf_ops.reglas + guard real de promoción.
CREATE ROLE service_role NOLOGIN;
CREATE SCHEMA lf_ops;
CREATE SCHEMA extensions;
CREATE TABLE lf_ops.reglas (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo text NOT NULL UNIQUE,
 categoria text NOT NULL,
 titulo text NOT NULL,
 descripcion text NOT NULL,
 razon text,
 valor_config jsonb,
 es_transversal boolean NOT NULL DEFAULT false,
 estado text NOT NULL DEFAULT 'CANDIDATO',
 origen text,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 pendiente_decision boolean NOT NULL DEFAULT false,
 pendiente_detalle text,
 created_by text
);
CREATE TABLE public.lf_rule_promotion_v1 (
 rule_code text,
 status text,
 request_snapshot_sha256 text
);
CREATE FUNCTION public.lf_asset_snapshot_sha_v1(p_type text, p_code text)
RETURNS text LANGUAGE sql STABLE AS $$
 SELECT md5(r.codigo || ':' || r.titulo || ':' || r.estado)
   FROM lf_ops.reglas r WHERE r.codigo=p_code AND p_type='REGLA'
$$;
-- Copia funcional de pg_get_functiondef() del guard live, no se modifica por la migración.
CREATE FUNCTION public.lf_rule_promotion_guard_v1()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public', 'extensions'
AS $function$
begin
 if NEW.estado='VIGENTE' and OLD.estado is distinct from 'VIGENTE' then
  if not exists(select 1 from public.lf_rule_promotion_v1 p where p.rule_code=OLD.codigo and p.status='APPROVED' and p.request_snapshot_sha256=public.lf_asset_snapshot_sha_v1('REGLA',OLD.codigo)) then
   raise exception 'LF_RULE_PROMOTION_REQUIRED:%',OLD.codigo; end if;
 end if;
 return NEW;
end $function$;
CREATE TRIGGER trg_lf_rule_promotion_guard_v1
BEFORE UPDATE OF estado ON lf_ops.reglas
FOR EACH ROW EXECUTE FUNCTION public.lf_rule_promotion_guard_v1();
