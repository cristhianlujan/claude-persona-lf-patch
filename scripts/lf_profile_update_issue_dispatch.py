#!/usr/bin/env python3
"""Issue-triggered entry for the governed ACTUALIZACION_PERFIL_LF caller.

Mirrors the issue entry of the profile admission flow (label on an open issue) so a
GPT-native or Claude-native session that cannot dispatch workflows can still start the
canonical profile-update operation. This script only validates the request and
re-dispatches the existing governed caller workflow on `main`; the OIDC identity,
the registry binding and every operation rule stay where they already are. It never
calls Supabase, never writes the profile and never selects a profile.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ISSUE_LABEL = "lf-profile-update-governed"
SCHEMA = "LF_PROFILE_UPDATE_REQUEST_V1"
WORKFLOW_FILE = "lf-customer-profile-creator-governance-caller.yml"
DISPATCH_REF = "main"
MAX_BODY_CHARS = 64000
MAX_INPUT_CHARS = 60000
TARGET_CODE = re.compile(r"PERFIL-[A-Z0-9][A-Z0-9-]{2,119}")
TARGET_PATH = re.compile(r"profiles/[a-z0-9][a-z0-9_-]{1,100}/[A-Za-z0-9_./-]{1,200}")
EXECUTION_ID = re.compile(r"EXEC-[A-Za-z0-9][A-Za-z0-9_-]{7,172}")
STEP_ID = re.compile(r"[a-z0-9_]{2,80}")
BASELINE_MODES = ("NOT_REQUIRED", "PRE_RESEARCH_ALWAYS")
# Issues opened from Claude Code sessions get this exact footer appended by the platform.
ALLOWED_ISSUE_FOOTER = re.compile(
    r"\s*(---\s*_Generated by \[Claude Code\]\(https://claude\.ai/code\)_\s*)?"
)
INIT_KEYS = {"schema_version", "action", "target_code", "target_path",
             "research_baseline_mode", "research_baseline_contract"}
BATCH_KEYS = {"schema_version", "action", "execution_id", "steps"}


def parse_issue_body(raw):
    """Parse exactly one JSON value; allow only whitespace or the known platform footer after it."""
    data, end = json.JSONDecoder().raw_decode(raw)
    if not ALLOWED_ISSUE_FOOTER.fullmatch(raw[end:]):
        raise ValueError("UPDATE_ISSUE_BODY_TRAILING_DATA")
    return data


def _check_trigger(event, env):
    issue = event.get("issue", {})
    expected_url = "https://api.github.com/repos/" + env["GITHUB_REPOSITORY"]
    if (env.get("GITHUB_EVENT_NAME") != "issues"
            or event.get("action") != "labeled"
            or event.get("label", {}).get("name") != ISSUE_LABEL
            or issue.get("state") != "open"
            or issue.get("pull_request") is not None
            or issue.get("repository_url") != expected_url):
        raise ValueError("UPDATE_ISSUE_TRIGGER_INVALID")
    raw = issue.get("body")
    if not isinstance(raw, str) or not raw.strip() or len(raw) > MAX_BODY_CHARS:
        raise ValueError("UPDATE_ISSUE_BODY_INVALID")
    return raw


def _validate_steps(steps):
    if not isinstance(steps, list) or not 1 <= len(steps) <= 64:
        raise ValueError("UPDATE_ISSUE_BATCH_SIZE_INVALID")
    seen = set()
    for item in steps:
        if not isinstance(item, dict):
            raise ValueError("UPDATE_ISSUE_STEP_INVALID")
        step_id = item.get("step_id")
        payload = item.get("evidence_payload")
        if (not isinstance(step_id, str) or not STEP_ID.fullmatch(step_id) or step_id in seen
                or not item.get("evidence_ref") or not isinstance(payload, dict)
                or "step_result" not in payload or "blocking_codes" not in payload):
            raise ValueError("UPDATE_ISSUE_STEP_INVALID")
        seen.add(step_id)


def governed_request(event, env):
    """Return the workflow_dispatch inputs for the governed caller. The caller and the
    database re-validate everything; this only keeps the transport bounded and exact."""
    data = parse_issue_body(_check_trigger(event, env))
    if not isinstance(data, dict) or data.get("schema_version") != SCHEMA:
        raise ValueError("UPDATE_ISSUE_SCHEMA_INVALID")
    action = data.get("action")
    if action == "profile_update_init":
        if set(data) != INIT_KEYS:
            raise ValueError("UPDATE_ISSUE_SCHEMA_INVALID")
        code, path = data["target_code"], data["target_path"]
        mode, contract = data["research_baseline_mode"], data["research_baseline_contract"]
        if (not isinstance(code, str) or not TARGET_CODE.fullmatch(code)
                or not isinstance(path, str) or not TARGET_PATH.fullmatch(path)
                or ".." in path.split("/") or mode not in BASELINE_MODES):
            raise ValueError("UPDATE_ISSUE_TARGET_INVALID")
        if mode == "PRE_RESEARCH_ALWAYS":
            if not isinstance(contract, dict):
                raise ValueError("UPDATE_ISSUE_BASELINE_CONTRACT_REQUIRED")
            contract_json = json.dumps(contract, separators=(",", ":"), ensure_ascii=False)
            if len(contract_json) > MAX_INPUT_CHARS:
                raise ValueError("UPDATE_ISSUE_INPUT_SIZE_INVALID")
        else:
            if contract is not None:
                raise ValueError("UPDATE_ISSUE_BASELINE_CONTRACT_FORBIDDEN")
            contract_json = ""
        return {"action": action, "target_code": code, "target_path": path,
                "research_baseline_mode": mode, "research_baseline_contract_json": contract_json}
    if action == "profile_update_record_batch":
        if set(data) != BATCH_KEYS:
            raise ValueError("UPDATE_ISSUE_SCHEMA_INVALID")
        execution_id = data["execution_id"]
        if not isinstance(execution_id, str) or not EXECUTION_ID.fullmatch(execution_id):
            raise ValueError("UPDATE_ISSUE_EXECUTION_ID_INVALID")
        _validate_steps(data["steps"])
        steps_json = json.dumps(data["steps"], separators=(",", ":"), ensure_ascii=False)
        if len(steps_json) > MAX_INPUT_CHARS:
            raise ValueError("UPDATE_ISSUE_INPUT_SIZE_INVALID")
        return {"action": action, "execution_id": execution_id, "steps_json": steps_json}
    raise ValueError("UPDATE_ISSUE_ACTION_INVALID")


def dispatch_command(inputs):
    cmd = ["gh", "workflow", "run", WORKFLOW_FILE, "--ref", DISPATCH_REF]
    for key, value in inputs.items():
        cmd += ["-f", f"{key}={value}"]
    return cmd


def main():
    try:
        event = json.loads(Path(os.environ["GITHUB_EVENT_PATH"]).read_text(encoding="utf-8"))
        inputs = governed_request(event, os.environ)
    except (ValueError, KeyError) as exc:
        print("::error title=UPDATE_ISSUE_REQUEST_INVALID::" + type(exc).__name__ + ":" + str(exc)[:200])
        return 1
    # Never print the steps or contract payloads in CI logs.
    print(json.dumps({"dispatching": WORKFLOW_FILE, "ref": DISPATCH_REF, "action": inputs["action"],
                      "target_code": inputs.get("target_code"), "execution_id": inputs.get("execution_id")}))
    if os.environ.get("LF_PROFILE_UPDATE_DISPATCH_DRY_RUN") == "1":
        return 0
    return subprocess.run(dispatch_command(inputs), check=False).returncode


if __name__ == "__main__":
    sys.exit(main())
