#!/usr/bin/env python3
"""Generate the governed key-pin migration for PG-01 OIDC (H1-C2).

Reads a GitHub Actions OIDC JWKS document (saved from
https://token.actions.githubusercontent.com/.well-known/jwks on a machine with access) and prints
one migration that pins its RSA signing keys into private.lf_pg01_oidc_jwks_v1. The migration is
then proposed by PR and applied only by the Merge Train. Nothing here touches a database.

Usage: python3 scripts/lf_pg01_oidc_jwks_pin_sql.py jwks.json > supabase/migrations/<v>_lf_pg01_oidc_jwks_pin_v1.sql
"""
import base64
import hashlib
import json
import re
import sys

ISSUER = "https://token.actions.githubusercontent.com"
B64URL = re.compile(r"^[A-Za-z0-9_-]+$")
KID = re.compile(r"^[A-Za-z0-9._:-]{1,200}$")


def b64url_len(v: str) -> int:
    return len(base64.urlsafe_b64decode(v + "=" * (-len(v) % 4)))


def render(raw: bytes) -> str:
    doc = json.loads(raw)
    keys = doc.get("keys")
    if not isinstance(keys, list) or not keys:
        raise SystemExit("JWKS_EMPTY")
    digest = hashlib.sha256(raw).hexdigest()
    rows = []
    for k in keys:
        if k.get("kty") != "RSA" or k.get("alg", "RS256") != "RS256" or k.get("use", "sig") != "sig":
            continue
        kid, n, e = str(k.get("kid", "")), str(k.get("n", "")), str(k.get("e", ""))
        if not (KID.match(kid) and B64URL.match(n) and B64URL.match(e)):
            raise SystemExit(f"JWKS_KEY_INVALID:{kid}")
        if b64url_len(n) < 256:
            raise SystemExit(f"JWKS_KEY_TOO_SHORT:{kid}")
        rows.append((kid, n, e))
    if not rows:
        raise SystemExit("JWKS_NO_RS256_KEYS")
    values = ",\n".join(
        f" ('{kid}','RSA',private.fn_lf_pg01_b64url_v1('{n}'),private.fn_lf_pg01_b64url_v1('{e}'),'{ISSUER}',"
        f"'{ISSUER}/.well-known/jwks#sha256={digest}')" for kid, n, e in rows)
    exact = " OR ".join(f"(kid='{kid}' AND n=private.fn_lf_pg01_b64url_v1('{n}') AND e=private.fn_lf_pg01_b64url_v1('{e}'))"
                        for kid, n, e in rows)
    return f"""-- LF / H1-C2 / PG-01: pin GitHub Actions OIDC signing keys (generated by scripts/lf_pg01_oidc_jwks_pin_sql.py).
-- Source JWKS sha256={digest}. Apply only through Router -> ACTUALIZACION_DB_LF -> PASE -> Train.
BEGIN;
DO $pre$ BEGIN
 IF to_regclass('private.lf_pg01_oidc_jwks_v1') IS NULL THEN RAISE EXCEPTION 'PG01_OIDC_JWKS_TABLE_MISSING'; END IF;
END $pre$;
INSERT INTO private.lf_pg01_oidc_jwks_v1(kid,kty,n,e,issuer,source_ref) VALUES
{values}
ON CONFLICT (kid) DO NOTHING;
DO $post$ BEGIN
 -- an existing kid with different key material fails closed (no silent replacement)
 IF (SELECT count(*) FROM private.lf_pg01_oidc_jwks_v1 WHERE active AND ({exact})) <> {len(rows)} THEN
   RAISE EXCEPTION 'PG01_OIDC_JWKS_PIN_MISMATCH'; END IF;
END $post$;
COMMIT;
"""


if __name__ == "__main__":
    sys.stdout.write(render(open(sys.argv[1], "rb").read()))
