#!/usr/bin/env python3
"""Generic OIDC-driven Router admission for EJECUCION_PERFIL_LF.

Forwards a Router context envelope (GATE2_DERIVED_PENDING_GOVERNED_ADMISSION) and
a native executor mode to the governed edge action. It never selects a profile,
never runs a model and never writes product data; authority stays in Supabase.
"""
import json
import os
import re
from pathlib import Path
import sys
import urllib.error
import urllib.parse
import urllib.request

EDGE_URL = os.environ.get("LF_PROFILE_EDGE_URL", "").rstrip("/")
AUDIENCE = "lf-profiles-governance-caller-v1"
ACTION = "router_profile_admit_context_v2"
EXECUTION_ACTION = "profile_execution_begin_from_router_context_v1"
NATIVE_MODES = ("GPT_NATIVE", "CLAUDE_NATIVE")
MAX_CONTEXT_CHARS = 60000
ISSUE_LABEL = "lf-profile-admit-governed"
# Issues opened from Claude Code sessions get this exact footer appended by the platform.
ALLOWED_ISSUE_FOOTER = re.compile(
    r"\s*(---\s*_Generated by \[Claude Code\]\(https://claude\.ai/code\)_\s*)?"
)


def parse_issue_body(raw):
    """Parse exactly one JSON value; allow only whitespace or the known platform footer after it."""
    data, end = json.JSONDecoder().raw_decode(raw)
    if not ALLOWED_ISSUE_FOOTER.fullmatch(raw[end:]):
        raise ValueError("ROUTER_ADMIT_ISSUE_BODY_TRAILING_DATA")
    return data


def call_json(url, payload, headers):
    headers = {"content-type": "application/json", **headers}
    req = urllib.request.Request(
        url, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            return response.status, json.load(response)
    except urllib.error.HTTPError as exc:
        try:
            return exc.code, json.load(exc)
        except ValueError:
            return exc.code, {"code": "NON_JSON_HTTP_FAILURE"}


def oidc():
    request_url = os.environ["ACTIONS_ID_TOKEN_REQUEST_URL"]
    request_token = os.environ["ACTIONS_ID_TOKEN_REQUEST_TOKEN"]
    delim = "&" if "?" in request_url else "?"
    url = f"{request_url}{delim}audience={urllib.parse.quote(AUDIENCE)}"
    req = urllib.request.Request(url, headers={"authorization": f"Bearer {request_token}"})
    with urllib.request.urlopen(req, timeout=30) as response:
        return json.load(response)["value"]


def _validate(context, mode):
    if not isinstance(context, dict):
        raise ValueError("ROUTER_ADMIT_CONTEXT_NOT_OBJECT")
    if (context.get("schema_version") != "LF_ROUTER_EXECUTION_PIPELINE_V1"
            or context.get("status") != "GATE2_DERIVED_PENDING_GOVERNED_ADMISSION"
            or context.get("transport_mode") != "CONTEXT_TRANSPORT"):
        raise ValueError("ROUTER_ADMIT_CONTEXT_ENVELOPE_INVALID")
    if mode not in NATIVE_MODES:
        raise ValueError("ROUTER_ADMIT_EXECUTOR_MODE_INVALID")
    return context, mode


def governed_request():
    """Validate bounded dispatch or issue data; the database re-validates everything."""
    if os.getenv("LF_PROFILE_ADMIT_REQUEST_MODE") == "ISSUE":
        event = json.loads(Path(os.environ["GITHUB_EVENT_PATH"]).read_text(encoding="utf-8"))
        issue = event.get("issue", {})
        expected_url = "https://api.github.com/repos/" + os.environ["GITHUB_REPOSITORY"]
        if (os.environ.get("GITHUB_EVENT_NAME") != "issues"
                or event.get("action") != "labeled"
                or event.get("label", {}).get("name") != ISSUE_LABEL
                or issue.get("state") != "open"
                or issue.get("pull_request") is not None
                or issue.get("repository_url") != expected_url):
            raise ValueError("ROUTER_ADMIT_ISSUE_TRIGGER_INVALID")
        raw = issue.get("body")
        if not isinstance(raw, str) or len(raw) > MAX_CONTEXT_CHARS + 2048:
            raise ValueError("ROUTER_ADMIT_ISSUE_BODY_INVALID")
        data = parse_issue_body(raw)
        if (not isinstance(data, dict)
                or set(data) != {"schema_version", "router_context", "executor_mode"}
                or data["schema_version"] != "LF_PROFILE_ROUTER_ADMIT_REQUEST_V1"):
            raise ValueError("ROUTER_ADMIT_ISSUE_SCHEMA_INVALID")
        if len(json.dumps(data["router_context"])) > MAX_CONTEXT_CHARS:
            raise ValueError("ROUTER_ADMIT_CONTEXT_SIZE_INVALID")
        return _validate(data["router_context"], data["executor_mode"])
    raw = os.environ.get("ROUTER_CONTEXT_JSON", "")
    if not raw or len(raw) > MAX_CONTEXT_CHARS:
        raise ValueError("ROUTER_ADMIT_CONTEXT_SIZE_INVALID")
    return _validate(json.loads(raw), os.environ.get("EXECUTOR_MODE", ""))


def admission_success(http_status, response, requested_mode):
    """Stage 06 is green only for a validated handoff with NO execution write."""
    if http_status != 200 or not isinstance(response, dict):
        return False
    result = response.get("result")
    if not isinstance(result, dict):
        return False
    return (
        response.get("outcome") == "PROFILE_HANDOFF_READY"
        and result.get("status") == "PROFILE_HANDOFF_READY"
        and result.get("write_performed") is False
        and result.get("execution_id") is None
        and result.get("executor_mode") == requested_mode
        and isinstance(result.get("profile_code"), str)
        and bool(result["profile_code"].strip())
        and isinstance(result.get("router_profile_handoff"), dict)
        and result.get("next_action") == "EJECUCION_PERFIL_LF_BEGIN_REQUIRED"
    )


def execution_success(http_status, response, requested_mode):
    """Stage 07 must create an actual governed EJECUCION_PERFIL_LF execution."""
    if http_status != 200 or not isinstance(response, dict):
        return False
    result = response.get("result")
    if not isinstance(result, dict):
        return False
    return (
        response.get("outcome") == "NATIVE_EXECUTION_READY"
        and result.get("status") == "NATIVE_EXECUTION_READY"
        and result.get("gate2_materialized") is True
        and result.get("executor_mode") == requested_mode
        and isinstance(result.get("execution_id"), str)
        and bool(result["execution_id"].strip())
        and isinstance(result.get("profile_code"), str)
        and bool(result["profile_code"].strip())
        and result.get("next_action") == "EXECUTE_PROFILE_IN_AUTHORIZED_NATIVE_CONTEXT"
    )

def main():
    try:
        context, mode = governed_request()
    except (ValueError, KeyError) as exc:
        print("::error title=ROUTER_ADMIT_REQUEST_INVALID::" + type(exc).__name__ + ":" + str(exc)[:200])
        return 1
    headers = {"authorization": f"Bearer {oidc()}"}
    code, response = call_json(
        EDGE_URL,
        {"action": ACTION, "context": context, "executor_mode": mode},
        headers,
    )
    admission = response.get("result") if isinstance(response.get("result"), dict) else {}
    admitted = admission_success(code, response, mode)
    print(json.dumps({
        "stage": "06_ADMISSION",
        "http_status": code,
        "outcome": response.get("outcome"),
        "profile_code": admission.get("profile_code"),
        "execution_id": admission.get("execution_id"),
        "write_performed": admission.get("write_performed"),
        "next_action": admission.get("next_action"),
    }, ensure_ascii=False))
    if not admitted:
        print("::error title=ROUTER_ADMIT_BLOCKED::" + json.dumps({
            "http_status": code, "outcome": response.get("outcome"),
            "code": response.get("code"), "result_status": admission.get("status"),
            "blocking_code": admission.get("blocking_code"),
        }, ensure_ascii=False))
        return 1

    # Stage 07 is a NEW authorized action: only EJECUCION_PERFIL_LF may write.
    code, response = call_json(
        EDGE_URL,
        {"action": EXECUTION_ACTION, "context": context, "executor_mode": mode},
        headers,
    )
    execution = response.get("result") if isinstance(response.get("result"), dict) else {}
    accepted = execution_success(code, response, mode)
    print(json.dumps({
        "stage": "07_EJECUCION_PERFIL_LF",
        "http_status": code,
        "outcome": response.get("outcome"),
        "execution_id": execution.get("execution_id"),
        "profile_code": execution.get("profile_code"),
        "executor_mode": mode,
        "next_action": execution.get("next_action"),
    }, ensure_ascii=False))
    if not accepted:
        print("::error title=PROFILE_EXECUTION_BEGIN_BLOCKED::" + json.dumps({
            "http_status": code, "outcome": response.get("outcome"),
            "code": response.get("code"), "result_status": execution.get("status"),
            "blocking_code": execution.get("blocking_code"),
        }, ensure_ascii=False))
    return 0 if accepted else 1

if __name__ == "__main__":
    sys.exit(main())
