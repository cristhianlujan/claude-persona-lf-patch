"""Native Step70 separate-call reviewer receipt validation.

This never invokes a model or fabricates a model call. It validates evidence
generated by a genuinely separate native LLM call, with its OWN prompt,
output schema, evaluator, evaluation result, and source artifact. A declarative
receipt is NOT a provider attestation and cannot be treated as one.

The server remains the final authority for 'independence_proven'.
"""
import re

SCHEMA_ID="LF_STEP70_SAME_LLM_REVIEW_OUTPUT_V1"
EVAL_ID="LF_STEP70_SAME_LLM_SEMANTIC_EVAL_V1"
VERDICT="PASS_INDEPENDENT_SEMANTIC"
SHA_RE=re.compile(r"^[0-9a-f]{64}$")
CALL_RE=re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{15,127}$")


def _required(condition,code):
    if not condition: raise ValueError(code)


def assess_separate_call_receipt(review, *, execution_id=None):
    """Returns independently checkable receipt shape; never invents provenance.

    It is deliberately not called from provider or workflow contexts that
    cannot attest that a second model call occurred.
    """
    _required(isinstance(review,dict),"STEP70_REVIEW_NOT_OBJECT")
    r=review.get("separate_model_call_receipt")
    if r is None:
        return {"status":"JUDGE_INDEPENDENCE_NOT_PROVEN",
                "producer_independence_proven":False,
                "reviewer_is_producer":True,"model_call_count":0,
                "independent_semantic_receipt_ref":None,
                "content_continuation_allowed":True}
    _required(isinstance(r,dict),"STEP70_SEPARATE_RECEIPT_NOT_OBJECT")
    required={"schema_version","receipt_ref","execution_id","model_id","model_call_id",
              "producer_call_ref","reviewer_call_ref","prompt_sha256",
              "producer_prompt_sha256","schema_id","producer_schema_id",
              "eval_id","producer_eval_id","eval_status",
              "model_call_count","candidate_sha256","scope_packet_sha256",
              "decision_body","provider_attestation"}
    _required(set(r)==required,"STEP70_SEPARATE_RECEIPT_CONTRACT_INVALID")
    _required(r["schema_version"]=="LF_STEP70_SAME_LLM_SEPARATE_CALL_RECEIPT_V1",
              "STEP70_SEPARATE_RECEIPT_VERSION_INVALID")
    _required(isinstance(r["execution_id"],str) and r["execution_id"].startswith("EXEC-PROFILE-GATE2-"),
              "STEP70_RUN_ID_MISSING")
    if execution_id:
        _required(r["execution_id"]==execution_id,"STEP70_RUN_ID_DRIFT")
    _required(isinstance(r["model_id"],str) and len(r["model_id"])>2,
              "STEP70_MODEL_UNIDENTIFIED")
    _required(isinstance(r["model_call_id"],str) and CALL_RE.fullmatch(r["model_call_id"]),
              "STEP70_SECOND_CALL_ID_INVALID")
    _required(all(isinstance(r[k],str) and r[k].startswith(("actions://","chatgpt-native://"))
              for k in ("receipt_ref","producer_call_ref","reviewer_call_ref")),
              "STEP70_SOURCE_REFS_INVALID")
    _required(r["producer_call_ref"] != r["reviewer_call_ref"]
              and r["receipt_ref"] != r["producer_call_ref"],
              "STEP70_CALL_NOT_SEPARATE")
    for field in ("prompt_sha256","producer_prompt_sha256",
                  "candidate_sha256","scope_packet_sha256"):
        _required(isinstance(r[field],str) and SHA_RE.fullmatch(r[field]),
                  "STEP70_"+field.upper()+"_INVALID")
    _required(r["prompt_sha256"]!=r["producer_prompt_sha256"],
              "STEP70_REUSED_PRODUCER_PROMPT")
    _required(r["schema_id"]==SCHEMA_ID and r["schema_id"]!=r["producer_schema_id"],
              "STEP70_SCHEMA_NOT_INDEPENDENT")
    _required(r["eval_id"]==EVAL_ID and r["eval_id"]!=r["producer_eval_id"],
              "STEP70_EVAL_NOT_INDEPENDENT")
    _required(type(r["model_call_count"]) is int and r["model_call_count"]>0,
              "STEP70_NO_MODEL_CALL_EVIDENCE")
    _required(r["eval_status"]=="PASS" and isinstance(r["decision_body"],dict)
              and r["decision_body"].get("verdict")==VERDICT,
              "STEP70_REVIEW_EVAL_NOT_PASS")
    _required(r["candidate_sha256"]==review.get("candidate_sha256")
              and r["scope_packet_sha256"]==review.get("scope_packet_sha256"),
              "STEP70_REVIEW_NOT_SOURCE_BOUND")
    _required(r["provider_attestation"] in (False,True),
              "STEP70_PROVIDER_ATTESTATION_UNREADABLE")
    try:
        from lf_step70_same_llm_eval_v1 import evaluate as evaluate_step70
    except ModuleNotFoundError:
        from scripts.lf_step70_same_llm_eval_v1 import evaluate as evaluate_step70
    reviewer_raw={"schema_id":r["schema_id"],"execution_id":r["execution_id"],
        "candidate_sha256":r["candidate_sha256"],
        "scope_packet_sha256":r["scope_packet_sha256"],
        "verdict":r["decision_body"].get("verdict"),
        "decision_body":r["decision_body"],
        "source_refs":review.get("source_refs",[])}
    local_eval=evaluate_step70(reviewer_raw,r["execution_id"],
        r["candidate_sha256"],r["scope_packet_sha256"])
    _required(local_eval["eval_status"]=="PASS",
        "STEP70_SEPARATE_EVALUATOR_NOT_PASS")
    # A request payload's 'provider_attestation': true is SELF-ASSERTED.
    # Until a trusted provider-side witness confirms this exact model_call_id,
    # do NOT set reviewer_is_producer=false or independence_proven=true.
    return {"status":"RECEIPT_FORMAT_VALID_PROVENANCE_UNATTESTED",
            "producer_independence_proven":False,
            "reviewer_is_producer":True,"model_call_count":0,
            "independent_semantic_receipt_ref":None,
            "receipt_ref_unverified":r["receipt_ref"],
            "model_call_id_unverified":r["model_call_id"],
            "schema_id":r["schema_id"],"eval_id":r["eval_id"],
            "evaluator_status":local_eval["eval_status"],
            "evaluator_raw_sha256":local_eval["review_raw_sha256"],
            "content_continuation_allowed":True}


MATERIAL_CODES={"STEP70_RUN_ID_DRIFT","STEP70_REVIEW_NOT_SOURCE_BOUND",
                "STEP70_REVIEW_EVAL_NOT_PASS","STEP70_SEPARATE_EVALUATOR_NOT_PASS",
                "STEP70_CALL_NOT_SEPARATE"}


def normalize_when_unverified(review, *, execution_id=None):
    """Conservatively downgrade a self-asserted independent PASS to content-only.

    Only read-only V3 content checks may continue under this mode; SQL will
    enforce that restriction. The original attempted receipt stays in the
    separate, optional audit artifact; do not claim provider provenance.
    """
    try:
        r=assess_separate_call_receipt(review, execution_id=execution_id)
    except ValueError as exc:
        if str(exc) in MATERIAL_CODES: raise
        r={"status":"JUDGE_INDEPENDENCE_NOT_PROVEN",
           "producer_independence_proven":False,
           "receipt_contract_error":str(exc),
           "content_continuation_allowed":True}
    if r["status"]=="JUDGE_INDEPENDENCE_NOT_PROVEN" or not r["producer_independence_proven"]:
        safe=dict(review)
        safe["review_mode"]="CURRENT_CONTEXT_REVIEW"
        safe["verdict"]="PASS_REVIEWED_CURRENT_CONTEXT"
        safe["reviewer_is_producer"]=True
        safe["producer_independence_proven"]=False
        safe["model_call_count"]=0
        safe["judge_independence_finding"]="JUDGE_INDEPENDENCE_NOT_PROVEN"
        safe.pop("separate_model_call_receipt",None)
        return safe,r
    return review,r
